## Lay out every frame position this project draws, card by card, for
## Architect to rule on.
##
##   Page exists to be argued with: each card carries identifier to quote
##     back, and mark saying whether it has been kept, dropped, or sent back
##     for mend.  Unmarked is unreviewed, never approved.
##   Verdict is given on picture, not on identifier.  So every ruled card's
##     drawing is pinned in `review.pins`, and build refuses to write page
##     whose ruled card has moved since: mend that reaches further than it
##     meant to stops here rather than shipping approval nobody gave.
##     Pins are regenerated by `tools/build.nim pins`, which is deliberate
##       second step -- verdict and pin are added together or not at all.
##   Sections `A` and `B` come from tables workbench already builds; `C` and
##     `D` are drawn here, and are only place project draws crossed pair's chain.

