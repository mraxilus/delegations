  var n = 0
  for c in 0 ..< SINGLES.len:
    body.add &"""<h3>{esc(SINGLES[c].name)}</h3><div class="grid wide">"""
    var seen = initTable[string, string]()   # svg -> id already given it
    var order: seq[string]
