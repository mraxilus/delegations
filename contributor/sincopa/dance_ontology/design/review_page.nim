  round looks like</b>, and it is the only frame of the eight where turning the
  other way draws anything different.</p><div class="grid">"""
  func armFor(side: Side): Arm =
    ## Say which drawn arm this side of lead is.
    if side == Side.Left: Arm.L else: Arm.R

  func armFor(site: Site): Arm =
    ## Same for hand of follow.
    if site == Site.LeftHand: Arm.L else: Arm.R

  func restsFacing(target: Frame): bool =
    ## Say whether this frame rests face-to-face rather than pillion lead.
    ##   Hold rests where its two connections run parallel and cross
    ##     nothing, which for same-name pair is pillion lead and not face to
    ##     face (rule 31).  Measured by `phaseOf`, never written down.
    ##   Hold with fewer than two connections has no such state to be at, so
    ##     it is counted from face to face like everything else.
    if target.countHolds < 2:
      return true
    var holds: Holds
    for side in Side:
      if target.hold[side].isSome:
        holds[armFor(side)] = some armFor(target.hold[side].get)
    phaseOf(holds) < 1e-9

  proc facingNote(target: Frame; twist: int; way: string): string =
    ## Say which facing this picture draws, and what it is turned from.
    let
      drawn = if twist == 0: "face-to-face" else: "pillion lead"
      rest = if restsFacing(target): "face-to-face" else: "pillion lead"
    if drawn == rest: &"{drawn}, at rest"
    elif way.len > 0: &"{drawn}, half a turn {way} from {rest}"
    else: &"{drawn}, half a turn from {rest}"

  func turnShows(target: Frame): bool =
    ## Say whether turning one way draws anything other way does not.
    renderFrame(target, HalfTurns(1)) != renderFrame(target, HalfTurns(-1))

  for i, target in FRAMES:
    for twist in [0, 1]:
      let way = if twist == 1 and turnShows(target): "clockwise" else: ""
      body.add card(&"A{i * 2 + twist + 1}", describe(target),
                    facingNote(target, twist, way),
                    renderFrame(target, HalfTurns(twist)))
  # And other way round, wherever turning that way draws different picture.
  # Appended rather than interleaved, so every identifier already ruled on
  # still names picture it was ruled on.
  var also = FRAMES.len * 2
  for target in FRAMES:
    let widdershins = renderFrame(target, HalfTurns(-1))
    if widdershins == renderFrame(target, HalfTurns(1)):
      continue
    inc also
    body.add card(&"A{also}", describe(target),
                  facingNote(target, 1, "anticlockwise"), widdershins)
  body.add "</div></section>"

