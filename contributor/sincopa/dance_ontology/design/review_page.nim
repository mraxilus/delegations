      steps: seq[tuple[pick, note, svg: string]]
      asksF: seq[string]
    for i in 0 ..< CHAIN.len - 1:
      let key = &"hw_{tag}_{i}"
      if key notin hh: continue
      asksF.add key
      steps.add ($(i + 1), CHAIN[i].name & " to " & CHAIN[i + 1].name, hh[key])
