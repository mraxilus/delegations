  for manner in Manner:
    let
      tag = MANNERS[manner].tag
      said = &"{MANNER_SAID[tag]} {chainWay(manner)}"
    if &"hc_{tag}" in hh:
      inc k
      body.add card(&"F{k}", said,
                    &"the whole chain, {CHAIN.len - 1} halves out and back",
                    hh[&"hc_{tag}"], asks = @[&"hc_{tag}"])
