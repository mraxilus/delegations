func esc(s: string): string =
  s.multiReplace(("&", "&amp;"), ("<", "&lt;"), (">", "&gt;"))

const
  MANNER_SAID = {"fa": "follow turns", "la": "lead turns",
              "fo": "follow orbits", "lo": "lead orbits"}.toTable
    ## Workbench's tags said in words, since sheet is read by eye.
  QUARTER_SAID = ["none", "a quarter", "a half", "three quarters"]
    ## How far round that manner has gone, counted in quarter turns.
  QUARTER_FROM = ["the start", "a quarter", "a half", "three quarters"]
    ## Same, worded for move that sets off from it.

const QUARTER_WAY = wayName(wayOf(HalfTurns(QUARTER)))
  ## Which way round every quarter on this page turns.
  ##   Read off turn itself rather than written down, so label cannot
  ##     outlive sign it describes.

func said(tag: string; quarter: int): string =
  ## Name one manner of turn, how far it has gone, and which way round.
  if quarter == 0: &"{MANNER_SAID[tag]} {QUARTER_SAID[quarter]}"
  else: &"{MANNER_SAID[tag]} {QUARTER_SAID[quarter]} {QUARTER_WAY}"

func unpinned(svg: string): string =
  ## Take off pixel size workbench pins each figure to for its own rows, so
  ## card decides how big picture is drawn: inline style would beat sheet.
  result = svg
  const OPEN = " style=\"width: "
  let at = result.find(OPEN)
  if at < 0:
    return
  let shut = result.find('"', at + OPEN.len)
  if shut < 0:
    return
  result = result[0 ..< at] & result[shut + 1 .. ^1]

proc checkReview*() =
  ## Check every card ruled on has pin holding it to what it was drawn as.
  ##   Verdict without pin is verdict nothing guards, which is how ruled
  ##     card came to move under one in first place.
  for id in KEPT:
    doAssert id in pinned,
      &"A kept card carries no pin; run `tools/build.nim pins`: got `{id}`."
  for id in DROPPED:
    doAssert id in pinned,
      &"A dropped card carries no pin; run `tools/build.nim pins`: got `{id}`."


func reviewParts*(single, hand: Parts): Parts =
  ## Collect every figure this page places: both walked pages' own parts,
  ## which it draws again at its own size, and crossed pair's.
  ##   Walked pages' parts are handed in, as their pages built them, rather
  ##     than routed again here.
  result = single
  for key, svg in hand:
    result[key] = svg
  for key, svg in pairTurnParts():
    result[key] = svg


func sheetOf(P: Parts): string =
  ## Build page, holding every card already ruled on to its own pin.

  func stepped(id: string; steps: seq[tuple[pick, note, svg: string]];
               asks: seq[string] = @[]): string =
    ## Stack several drawings in one cell, one shown at time, with button
    ## apiece.
    ##   Each step carries sim's own tag, not cell.  Cell that folds six edges
    ##     together and is marked by worst of them paints five reachable edges
    ##     red for sake of sixth, and reader asking why easy one is refused is
    ##     reading tag that was never about it.
    ##   Radio button and sibling rule do switching, so cell needs no script:
    ##     page stays markup browser can draw with nothing running.
    ##   Every step keeps its own note under its own picture, since note is
    ##     what tells one step from next.
    var
      picks = ""
      frames = ""
      buttons = ""
    for i, step in steps:
      let at = &"{id}-{i + 1}"
      picks.add &"""<input type="radio" name="{id}" id="{at}""" &
        (if i == 0: "\" checked>" else: "\">")
      let says = if i >= asks.len or asks[i] notin modelled: ""
                 elif not modelled[asks[i]]: """<em class="tag nomodel">not modelled</em>"""
                 elif id in CONFIRMED: """<em class="tag model">modelled</em>"""
                 else: """<em class="tag unsure">unconfirmed</em>"""
      frames.add &"""<div>{unpinned(step.svg)}{says}""" &
        &"""<span class="step">{esc(step.note)}</span></div>"""
      buttons.add &"""<label for="{at}">{esc(step.pick)}</label>"""
    &"""{picks}<div class="frames">{frames}</div>""" &
      &"""<div class="picks">{buttons}</div>"""

  func card(id, label, note, art: string; drawings: seq[string];
            switching = false; asks: seq[string] = @[]): string =
    ## Set one cell beside its identifier, carrying whatever has been ruled
    ## on it.  Unmarked is unreviewed, not approved.
    let
      flawed = id in FLAWED
      kept = id in KEPT
      dropped = id in DROPPED
      mark = if flawed: " flawed" elif kept: " kept"
             elif dropped: " dropped" else: ""
      badge = if flawed: """<em class="tag mend">mend</em>"""
              elif kept: """<em class="tag keep">kept</em>"""
              elif dropped: """<em class="tag drop">drop</em>"""
              else: ""
      # Sim's own tag, drawn outlined where Architect's is solid, so ruling by
      # eye and reading by engine are never taken for one another.  It sits in
      # other corner, and outside drawing, so no pin moves by its being here.
      # Cell folding several pictures together stands for several questions, and
      # is reached only where sim reaches every one of them.  Card nothing has
      # been asked about carries no tag at all.
      put = if asks.len > 0: asks else: @[id]
      known = put.filterIt(it in modelled)
      reached = known.len > 0 and known.allIt(modelled[it])
      # Cell's own colour says how far it has got: green only where it is kept,
      # wholly reached and confirmed; amber where sim reaches all or part of it
      # and Architect has not yet confirmed; red where sim reaches none of it.
      # Badges keep saying which of two tags each is.
      stand = if known.len == 0: ""
              elif reached and id in CONFIRMED: " met"
              elif reached or known.anyIt(modelled[it]): " part"
              else: " unmet"
      says = if switching or known.len == 0: ""
             elif not reached: """<em class="tag nomodel">not modelled</em>"""
             elif id in CONFIRMED: """<em class="tag model">modelled</em>"""
             else: """<em class="tag unsure">unconfirmed</em>"""
    # Questions cell stands for are written on it, so viewer page laying sim
    # beside each cell can find its still by question and not by cell's name.
    # Verdict was given on pictures, so picture that moved under one carries
    # approval it was never given.  Card holds itself to what it was drawn
    # as when it was ruled on, and mend reaching further than it meant to
    # stops here rather than shipping.  Cell holding several drawings is
    # held to all of them, since verdict on it is verdict on all.
    if kept or dropped:
      doAssert $hash(drawings.join("")) == pinned.getOrDefault(id),
        &"A card already ruled on has been re-drawn: `{id}`.  Either the " &
          "mend is too wide, or that verdict has to go back."
    &"""<figure class="pic{mark}{stand}" data-asks="{put.join(" ")}"><div class="art""" &
    (if switching: " steps" else: "") & &"""">{art}{badge}{says}</div>""" &
    &"""<figcaption><code>{esc(id)}</code><b>{esc(label)}</b>""" &
    (if note.len > 0: &"""<span>{esc(note)}</span>""" else: "") &
    (if flawed: &"""<span class="fix">{esc(FLAWED[id])}</span>""" else: "") &
    "</figcaption></figure>"

  func card(id, label, note, svg: string; asks: seq[string] = @[]): string =
    ## Set one drawing in cell of its own.
    card(id, label, note, unpinned(svg), @[unpinned(svg)], asks = asks)

  func card(id, label, note: string;
            steps: seq[tuple[pick, note, svg: string]];
            asks: seq[string] = @[]): string =
    ## Set several drawings in one cell, switched between by button.
    card(id, label, note, stepped(id, steps, asks),
         steps.mapIt(unpinned(it.svg)), switching = true, asks = asks)

  var body = ""

  # `A`. Standard diagram: eight frames, two twist parities, and that is all of it.
  body.add """<section id="standard"><h2>A &middot; The standard diagram</h2>
  <p class="lede">Every drawing in this project is one of these, and a table built at compile
  time holds them all. The drawing reads the frame hold, the parity of the twist, and the way
  the couple turned. It never reads the level of an arm, and it never reads contact.</p>
  <p class="how"><b>The diagram cannot name the facing.</b> The model holds eight facings, which
  take three bits. The diagram draws only half turns, which reach four of them, and it reads one
  bit: the parity of the twist. So the drawing commits to one facing of each pair: it turns the
  follow, and never the lead. Every card below names the facing it draws, and not the facing the
  model knows.</p>
  <p class="how"><b>Each frame counts from its own rest.</b> Rest is the facing where the
  connections of that hold run parallel and cross nothing. A same-name pair rests <b>Pillion</b>
  rather than Face-to-face. So A10 and A12 read <i>at rest</i>, and A9 and A11 read <i>half a turn
  from Pillion</i>. A card names a way round only where the other way
  round draws a different picture, which is A16 and A17 alone.</p>
  <p class="how"><b>A crossing breaks at the arm that goes under.</b> The drawing cuts that
  arm at the middle, and the <code>over</code> field of the frame says which arm it is. A16
  carries no such field: its two connections run parallel at rest, and they cross only once
  the follow turns. Which arm ends over depends on the way the follow turned, so A16 and A17 draw
  the two ways. They are the one frame of the eight where the way round changes the
  picture.</p><div class="grid">"""
  func armFor(side: Side): Arm =
    ## Say which drawn arm this side of lead is.
    if side == Side.Left: Arm.L else: Arm.R

  func armFor(site: Site): Arm =
    ## Same for hand of follow.
    if site == Site.LeftHand: Arm.L else: Arm.R

  func restsFacing(target: Frame): bool =
    ## Say whether this frame rests Face-to-face rather than Pillion.
    ##   Hold rests where its two connections run parallel and cross
    ## nothing, which for same-name pair is Pillion and not Face-to-
    ##     face (rule 31).  Measured by `phaseOf`, never written down.
    ##   Hold with fewer than two connections has no such state to be at, so
    ##     it is counted from face to face like everything else.
    if target.countHolds < 2:
      return true
    var holds: Holds
    for side in Side:
      if target.hold[side].isSome:
        holds[armFor(side)] = some armFor(target.hold[side].get)
    phaseOf(holds) < 1e-9

  proc facingNote(target: Frame; twist: int; way: string): string =
    ## Say which facing this picture draws, and what it is turned from.
    let
      drawn = if twist == 0: "Face-to-face" else: "Pillion"
      rest = if restsFacing(target): "Face-to-face" else: "Pillion"
    if drawn == rest: &"{drawn}, at rest"
    elif way.len > 0: &"{drawn}, half a turn {way} from {rest}"
    else: &"{drawn}, half a turn from {rest}"

  func turnShows(target: Frame): bool =
    ## Say whether turning one way draws anything other way does not.
    renderFrame(target, HalfTurns(1)) != renderFrame(target, HalfTurns(-1))

  for i, target in FRAMES:
    for twist in [0, 1]:
      let way = if twist == 1 and turnShows(target): "clockwise" else: ""
      body.add card(&"A{i * 2 + twist + 1}", describe(target),
                    facingNote(target, twist, way),
                    renderFrame(target, HalfTurns(twist)))
  # And other way round, wherever turning that way draws different picture.
  # Appended rather than interleaved, so every identifier already ruled on
  # still names picture it was ruled on.
  var also = FRAMES.len * 2
  for target in FRAMES:
    let widdershins = renderFrame(target, HalfTurns(-1))
    if widdershins == renderFrame(target, HalfTurns(1)):
      continue
    inc also
    body.add card(&"A{also}", describe(target),
                  facingNote(target, 1, "anticlockwise"), widdershins)
  body.add "</div></section>"

  # `B`. Single-hand turns: what animated page walks through.
  let st = P
  body.add """<section id="single"><h2>B &middot; Single-hand turn positions</h2>
  <p class="lede">These are the positions that the single-hand turns page walks between. Two
  manners of one family stand at the same four positions, and manners of two families meet
  where they rest. So every repeat folds into one card, and each card names the manners and
  the quarters that land on it. Two manners are axis turns, one of the follow and one of the
  lead. Two are orbits, the follow round the lead and the lead round the follow. A quarter
  says how far round that manner has gone.</p>"""
  var n = 0
  for c in 0 ..< SINGLES.len:
    body.add &"""<h3>{esc(SINGLES[c].name)}</h3><div class="grid wide">"""
    var seen = initTable[string, string]()   # svg -> id already given it
    var order: seq[string]
    var whose = initTable[string, seq[string]]()
    var asked = initTable[string, seq[string]]()  # svg -> questions it stands for
    for manner in Manner:
      for q in 0 ..< QUARTERS_ROUND:
        let key = &"st_{MANNERS[manner].tag}_{c}_{q}"
        if key notin st: continue
        let svg = st[key]
        if svg notin seen:
          inc n
          seen[svg] = &"B{n}"
          order.add svg
        whose.mgetOrPut(svg, @[]).add said(MANNERS[manner].tag, q)
        asked.mgetOrPut(svg, @[]).add &"st_{MANNERS[manner].tag}_{c}_{q}"
    for svg in order:
      # Where every manner lands on one picture, say so once rather than four times.
      let who = if whose[svg].len == MANNERS.len and
                   QUARTER_SAID[0] in whose[svg][0]: "every manner, before it starts"
                else: whose[svg].join(" \u00B7 ")
      body.add card(seen[svg], SINGLES[c].name, who, svg, asks = asked[svg])
    body.add "</div>"
  body.add "</section>"

  func windNote(note: string; wind: float; zero = ""): string =
    ## Say how far position stands from where its chain rests, and which way
    ## round.
    ##   Way comes from `wayOf`, so page and vocabulary cannot drift apart on
    ##     which sign is which.
    ##   `zero` replaces resting note for chain whose rest is not app's frame,
    ##     which `chainFor` names for hand-to-hand chain it was written for.
    if abs(wind) < 1e-9: (if zero.len > 0: zero else: note)
    else: note & " " & wayName(wayOf(HalfTurns(wind * 2)))


  # `C`. Chain two-hand page walks.
  let hh = P
  const PAIRED: Holds = [some Arm.L, some Arm.R]
  let
    dualPhase = phaseOf(PAIRED)
    dualChain = chainFor(PAIRED)
  # One scale for both chains, so section `C` and section `D` compare directly.
  var half = 0.0
  for position in CHAIN:
    half = max(half, extent(handPose(position.wind), captions = false))
  for position in dualChain:
    half = max(half, extent(posedAt(position.wind, dualPhase), captions = false))

  body.add """<section id="chain"><h2>C &middot; The cross-name chain, Face-to-face at rest</h2>
  <p class="lede">The chain stands in seven places, half a turn apart, and the hand-to-hand page
  walks along it. Each place carries a twist as a real number rather than a count of half turns,
  which the standard diagram cannot hold. The facing alternates along the chain: Face-to-face at
  the whole turns, and Pillion at the halves. Every caption says how far round the place
  stands from the frame, <b>clockwise seen from above</b>. That is how the drawings see the
  couple, and it names one turn whichever dancer walks it. Section D is drawn at this scale, so
  the two chains stand against each other.</p><div class="grid wide">"""
  for i, position in CHAIN:
    body.add card(&"C{i + 1}", position.name, windNote(position.note, position.wind),
      renderFigure("tiny", HAND_TO_HAND, ABOVE_BOTH, captions = false,
        pose = some handPose(position.wind), half = some half,
        twist = windTwist(position.wind), clear_marks = true))
  body.add "</div></section>"


  # `D`. Dual chain: same hold, follow starting away.
  body.add &"""<section id="paired"><h2>D &middot; The same-name chain, Pillion at rest</h2>
  <p class="lede">This hold joins the left of the lead to the left of the follow, and right to
  right. It walks the chain of section C, read half a turn along. So it runs parallel
  <b>Pillion</b> rather than Face-to-face, and its phase measures {dualPhase} where the phase of
  the other chain measures {HAND_PHASE}. Its facing alternates the other way about: Pillion at the
  whole turns, and Face-to-face at the halves. No page in this project walks this
  chain.</p><div class="grid wide">"""
  for i, position in dualChain:
    body.add card(&"D{i + 1}", position.name,
      windNote(position.note, position.wind,
             zero = "this hold's own parallel state"),
      renderFigure("tiny", PAIRED, ABOVE_BOTH, captions = false,
        pose = some posedAt(position.wind, dualPhase), half = some half,
        twist = windTwist(position.wind), clear_marks = true))
  body.add "</div></section>"

