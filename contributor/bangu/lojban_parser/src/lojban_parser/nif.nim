func indexQuoted*(letters: openArray[string]): int =
  ## dunda lo namcu pe lo valsi pe lo gerna valsi pe `ZOI` .i le valsi cu vasru lo se ciska poi zo
  ##   zoi .a zo la'o cu sitna ke'a .i le fancu cu pilno lo lerfu pe lo valsi pe le gerna valsi gi'e
  ##   tcidu `h` ta'i lo nu tcidu `'` .i le valsi cu remoi lo valsi poi se lidne lo cmavo be zoi gy.
  ##   ZOI .gy. .i ro cmavo be zoi gy. BAhE .gy. poi basna le cmavo cu lidne le cmavo to le javni pe
