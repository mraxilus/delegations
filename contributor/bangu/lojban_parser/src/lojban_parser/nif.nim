func addRule(
    text: var string, node: Node, top: int, reading: ReadingText | ReadingMarked | LeavesNif
) =
  ## jmina lo javni poi se cmene ku'o lo se ciska .i va'o lo nu lo javni cu vasru pa javni po'o kei
  ##   le fancu cu jmina le se vasru ta'i lo pagbu be lo porsi poi krasi bu'u `top` .i lo javni poi
  ##   fanmo lo porsi cu ciska lo tcita pe vo'a ge'u ce'o `top` ce'o lo jgena pe vo'a .i va'o lo nu
  ##   le porsi cu se krasi le javni poi fanmo le porsi kei `top` na se ciska
  ##   .i lo srera jgena cu fanmo lo porsi poi gapru le srera jgena .i le srera jgena cu ciska
  ##     `srera` ce'o lo stuzi poi le gerna cu sisti bu'u ke'a ku'o ce'o lo tcita be lo javni poi
  ##     sisti bu'u le stuzi ku'o be'o ce'o `nitcu` joi lo gerna valsi poi se tcidu bu'u le stuzi
  let is_chain = node.stop.isNone and node.children.len == 1 and
    not node.children[0].is_terminal and node.children[0].stop.isNone
  if is_chain:
    text.addRule(node.children[0], top, reading)
    return
  text.add '('
  if node.stop.isSome:
    when reading is ReadingMarked or reading is LeavesNif:
      text.add TAG_ERROR
      text.add ' '
      text.add $(when reading is LeavesNif: node.stop.get.at else: reading.byteAt(node.stop.get.at))
      text.add ' '
    else:
      doAssert false, "Reading that reads should hold no error node."
  text.add node.rule.tag
  if node.stop.isNone and top != node.number:
    text.add ' '
    text.add $top
  if node.stop.isSome:
    text.add " ("
    text.add TAG_EXPECTS
    for k in 0 ..< node.stop.get.expected.len:
      text.add ' '
      text.add ($node.stop.get.expected[k]).tag
    text.add ')'
  for k in 0 ..< node.children.len:
    text.add ' '
    text.addNode(node.children[k], reading)
  text.add ')'




func addNode(text: var string, node: Node, reading: ReadingText | ReadingMarked | LeavesNif) =
  ## jmina lo jgena pe lo tricu lo se ciska .i va'o lo nu le jgena cu javni kei le fancu cu jmina lo
  ##   porsi poi krasi bu'u le jgena gi'e porsi lo javni poi se cmene .i va'o lo nu le jgena cu
  ##   gerna valsi kei le fancu cu jmina lo klesi ce'o lo stuzi .e bo lo lerfu pe ro valsi .i va'o
  ##   lo nu no gerna valsi cu vasru lo pagbu kei lo valsi pe le pagbu cu se lidne `rivbi` ce'o lo
  ##   ve pruce poi to'e curmi le pagbu .i le ve pruce po'u `Stream` cu se lidne lo nu to'e curmi pe
  ##   lo porsi be lo valsi
  if not node.is_terminal:
    text.addRule(node, node.number, reading)
    return
  when reading is LeavesNif:
    text.addLeaf(reading.terminals[node.at])
  else:
    text.addUnit(node, reading)




func toNif*(reading: ReadingText): string =
  ## ciska lo tricu pe lo se tcidu fi lo se ciska be fi la'o gy. NIF .gy. .i lo minde cu lidne lo
  ##   jgena pe le javni po'u `text` .i le jgena cu lidne lo fanmo be lo linji
  doAssert reading.is_read, "Reading should read, since refusal holds no tree; got refusal `" &
    $reading.refusal & "`."
  result = HEADER
  result.addNode(reading.tree, reading)
  result.add '\n'


func toNif*(reading: ReadingMarked): string =
  ## ciska lo tricu pe lo se tcidu poi sinxa ro srera ku'o fi lo se ciska be fi la'o gy. NIF .gy. .i
  ##   lo minde cu lidne lo genja jgena .i le genja jgena cu lidne lo fanmo be lo linji .i va'o lo
  ##   nu le se ciska cu se tcidu kei le se ciska be fi la'o gy. NIF .gy. cu mintu lo se ciska be
  ##   `readText`
  result = HEADER
  result.addNode(reading.tree, reading)
  result.add '\n'


func toNif*(node: Node, reading: ReadingMarked): string =
  ## ciska pa jgena pe lo tricu pe lo se tcidu fi la'o gy. NIF .gy. ta'i lo nu lo se ciska be fi
  ##   la'o gy. NIF .gy. cu ciska le jgena .i le fancu cu ciska no minde .i ne'i lo jmive se ciska
  ##   lo jgena pe ro pagbu be le se ciska cu se benji ne'i lo linji pe vo'a to `live.nim` toi
  result.addNode(node, reading)


func toNifParts*(reading: ReadingMarked): string =
  ## ciska lo se ciska be fi la'o gy. NIF .gy. be'o poi ro jgena pe ke'a cu panzi lo genja be le se
  ##   tcidu .i ro jgena cu zvati lo linji pe vo'a .i le jgena cu du lo jgena pe ro pagbu be le se
  ##   ciska be'o ge'u .e ro pagbu poi se to'e curmi gi'e zvati lo jbini be le pagbu be le se ciska
  ##   to `readTextParts` toi .i lo jmive se ciska cu ciska le jgena ta'i le mintu
  result = HEADER
  for k in 0 ..< reading.tree.children.len:
    result.addNode(reading.tree.children[k], reading)
    result.add '\n'


func toNif*(trees: openArray[Node], leaves: LeavesNif): string =
  ## ciska ro tricu poi se rapli zbasu fi la'o gy. NIF .gy. ku'o ta'i lo jgena pe lo se ciska be fi
  ##   la'o gy. NIF .gy. ta'i lo nu ciska lo se tcidu .i lo minde cu lidne ro tricu .i ro tricu cu
  ##   zvati lo linji pe vo'a .i se ki'u bo lo nu jmina lo pagbu cu ciska lo tricu pe lo nu tcidu le
  ##   mulno se ciska .a ro tricu poi le nu jmina cu dunda ke'a va'o lo nu lo srera cu stali to
  ##   `merge.nim` toi
  result = HEADER
  for k in 0 ..< trees.len:
    result.addNode(trees[k], leaves)
    result.add '\n'
