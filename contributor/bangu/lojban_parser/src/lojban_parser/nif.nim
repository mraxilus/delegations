func escaped(text: string, is_identifier: bool): string =
  ## ciska lo se ciska .i lo basti sinxa `\xx` cu basti ro stuzi poi la'o gy. NIF .gy. na vasru ke'a
  ##   ta'i lo nu stali .i `\xx` cu ciska lo stuzi ta'i re lerfu pe li paxa gi'e pilno lo barda
  ##   lerfu .i ne'i lo cmene le basti sinxa cu basti ro stuzi poi mleca li parebi gi'e na lerfu
  ##   gi'e na namcu gi'e na du `_` .i ne'i lo lerpoi le basti sinxa cu basti ro minde lerfu poi na
  ##   du `#` gi'e na du `:` ku'o .e ro stuzi poi mleca lo kunti lerfu ku'o .e la'o gy. DEL .gy. .i
  ##   ro stuzi poi na mleca li parebi cu stali
  for c in text:
    let is_kept =
      if ord(c) >= 128: true
      elif is_identifier: c in KEPT_IDENTIFIER
      else: ord(c) >= ord(' ') and ord(c) != 127 and (c notin CONTROLS or c in KEPT_STRING)
    if is_kept: result.add c
    else:
      result.add '\\'
      result.add toHex(ord(c), 2)


func tag(name: string): string =
  ## ciska lo cmene be lo javni .a lo klesi be lo gerna valsi ta'i lo tcita .i `_` cu basti ro `-`
