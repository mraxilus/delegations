func addLeaf(text: var string, terminal: TerminalNif) =
  ## jmina lo gerna valsi poi la'o gy. NIF .gy. cu dunda ke'a ku'o lo se ciska ta'i lo nu lo se
  ##   tcidu cu ciska lo gerna valsi .i lo klesi .a `rivbi` joi bo lo cmene pe `rivbi` cu lidne lo
  ##   stuzi .e lo lerfu pe ro valsi .i `h` cu basti ro `'` .i ku'i lo se ciska poi lo nu sitna cu
  ##   vasru ke'a ku'o .e lo se ciska valsi poi le porsi be lo valsi cu to'e curmi ke'a cu stali
  var letters: seq[string]
  for k in 0 ..< terminal.words.len: letters.add terminal.words[k].letters
  let
    names = terminal.terminal.split(' ')
    is_kept = names.len > 1 and names[0] == TAG_UNREAD and names[1] == RefusalText.Stream.spelling
    quoted = (if names[0] == $Selmaho.Zoi: some(letters.indexQuoted) else: none(int))
  text.add '('
  text.add names[0].tag
  for k in 1 ..< names.len:
    text.add ' '
    text.add names[k].tag
  for k in 0 ..< terminal.words.len:
    template word: untyped = terminal.words[k]
      ## drata cmene le valsi .i `let` cu zbasu lo fukpi be le valsi va'o lo nu fanva fi la'o gy.
      ##   JavaScript .gy.
    let is_quoted = quoted == some(k)
    text.add ' '
    text.add $word.start
    text.add ' '
    text.add $word.finish
    text.add " \""
    text.add escaped(
      if is_kept or is_quoted: word.letters else: word.letters.replace('\'', 'h'),
      is_identifier = false,
    )
    text.add '"'
  text.add ')'


