##     lo cmavo poi lo karsna cu krasi ke'a ku'o po'o ki'u lo nu `CLL 3.4` cu to'e curmi le sakli
##     karsna ne'i ro valsi poi na sepli .i `Cy` .e `y` .e `y'y` cu lerfu cmavo to `CLL 4.2` .e
##     `CLL 17.2` toi
