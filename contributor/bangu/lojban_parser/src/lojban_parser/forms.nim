##   .i ja'i `CLL 4.2` .e `CLL 3.3` lo cmavo gunma cu se fendi pu ro zunsna gi'e se fendi bu'u ro
##     lerfu po'u denpa bu .i lo cmavo cu vasru su'e pa zunsna noi pamoi .i lo cmavo poi lo karsna
