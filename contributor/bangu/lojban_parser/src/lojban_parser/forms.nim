## facki lo tarmi be lo lojbo valsi .e lo rafsi ta'i lo nu `CLL 4` cu ciska le tarmi sepi'o
##   zoi gy. C .gy. .e zoi gy. V .gy.
##
##   |----------|----------|--------------------------------------------------------|------------|
##   | lo cmima | lo tarmi | lo smuni                                               | lo ckupau  |
##   |----------|----------|--------------------------------------------------------|------------|
##   | `Cvc`    | `CVC`    | lo cmalu rafsi poi no roi fanmo lo lujvo               | `4.6`      |
##   | `Ccv`    | `CCV`    | lo cmalu rafsi .i `CC` cu ka'e krasi lo valsi          | `4.6`      |
##   | `Cvv`    | `CVV`    | lo cmalu rafsi poi se tarmi `CV'V` .a `CVV`            | `4.6`      |
##   |          |          | `VV` cu du pa le vo karsna remei po'u `ai ei oi au`    |            |
##   | `Cvcc`   | `CVC/C`  | lo rafsi poi vasru vo lerfu gi'e no roi fanmo lo lujvo | `4.6`      |
##   |          |          | le rafsi cu se krasi lo gismu poi se tarmi `CVCCV`     |            |
##   | `Ccvc`   | `CCVC`   | lo rafsi poi vasru vo lerfu gi'e no roi fanmo lo lujvo | `4.6`      |
##   |          |          | le rafsi cu se krasi lo gismu poi se tarmi `CCVCV`     |            |
##   | `Cvccv`  | `CVC/CV` | lo gismu .a lo rafsi be ri be'o poi vasru mu lerfu     | `4.4, 4.6` |
##   |          |          | le rafsi cu fanmo ro lujvo poi vasru ke'a              |            |
##   | `Ccvcv`  | `CCVCV`  | lo gismu .a lo rafsi be ri be'o poi vasru mu lerfu     | `4.4, 4.6` |
##   |          |          | le rafsi cu fanmo ro lujvo poi vasru ke'a              |            |
##   |----------|----------|--------------------------------------------------------|------------|
##
##   lo sinxa pe la'o gy. CLL .gy. cu ralju tadji lo nu ciska lo cmene to `Article III.1` toi .i
##     zoi gy. C .gy. cu sinxa lo zunsna .i zoi gy. V .gy. cu sinxa lo karsna .i `/` cu sinxa lo
##     midju zunsna remei poi bilga lo ka se curmi po'o to `CLL 3.6` toi .i lo re lamji zunsna poi
##     krasi le tarmi cu bilga lo ka ka'e krasi lo valsi to `CLL 3.7` toi .i ro cmima be `Form` cu
##     ciska le sinxa ta'i la'o gy. Pascal case .gy. to `Article V.11` toi
##   .i `Cvv` cu sinxa `CV'V` .e `CVV` noi vasru lo karsna remei ku'o ki'u lo nu ro le re tarmi cu
##     ka'e zvati ro stuzi poi `CVV` cu ka'e zvati ke'a .i zoi gy. ' .gy. cu vajni lo namcu po'o to
##     `CLL 4.12` toi .i le namcu cu tcidu zoi gy. ' .gy. fi lo lerfu
##   .i lo tarmi cu jdice fi lo lerfu po'o gi'e no roi retsku fi lo vlaste .i mupli fa lo nu `dri`
##     cu se tarmi `Ccv` .iju lo liste cu dunda `dri` lo valsi .i se ki'u bo lo tarmi be lo valsi cu
##     sepli lo vlaste .i lo cipra cu ka'e cipra fi lo tarmi po'o .a lo vlaste po'o
##   .i `Kind` cu fendi lo valsi lo klesi pe `CLL 4.1` sepi'o lo lerfu po'o ta'i lo nu `CLL 4.2`
##     bi'o `CLL 4.8` cu skicu ro klesi .i lo liste cu dunda lo smuni gi'e no roi dunda lo klesi
##   .i le vi datnyvei cu vasru lo javni pe lo cmene to `CLL 4.8` toi .e lo javni pe lo fu'ivla to
##     `CLL 4.7` toi vu'o poi nitcu lo lerfu po'o .i lo javni pe lo zunsna remei to `CLL 3.6` toi cu
##     srana ro le re klesi .i lo javni pe lo zunsna cimei to `CLL 3.7` toi cu srana lo fu'ivla po'o
##     .i le javni cu srana ji'a lo zunsna gunma poi krasi lo fu'ivla ku'o .e lo du'u lo cmene na
##     ka'e vasru zo la .a zo doi
##     .i lo javni poi nitcu lo drata valsi cu zvati `fuhivla.nim` .i mupli fa lo javni pe lo valsi
##       gunma .e lo cipra pe zoi gy. slinku'i .gy.
##   .i le vi datnyvei cu vasru ji'a lo javni pe lo denpa zi'e poi nitcu lo lerfu po'o to `CLL 4.9`
##     toi .i se ki'u bo `fuhivla.nim` .e `stream.nim` cu pilno le javni .i `stream.nim` cu jmina lo
##     javni pe lo nu basna
##   .i ja'i `CLL 4.2` lo cmavo cu vasru lo porsi be lo karsna .i pa zunsna cu ka'e lidne le porsi
##     .i lo pamoi pagbu be le porsi cu du pa karsna .a pa karsna remei .i zoi gy. ' .gy. cu lidne
