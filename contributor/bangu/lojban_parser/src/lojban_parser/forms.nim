func pairForbidden*(text: string): Option[string] =
  ## facki lo pamoi zunsna remei poi `CLL 3.6` cu to'e curmi ke'a ku'o ne'i le se ciska .i dunda
  ##   `none` va'o lo nu ro zunsna remei cu se curmi .i lo cmene cu nitcu di'u po'o to `CLL 4.8` toi
  ##   .i mupli fa lo nu zo NEderlants cu vasru lo zunsna cimei po'u `nts` .i ku'i `CLL 4.8` cu
  ##   cusku lo du'u le cmene cu drani
  for i in 0 ..< text.high:
    if not (text[i].isConsonant and text[i + 1].isConsonant): continue
    if not isPairPermissible(text[i], text[i + 1]): return some(text[i .. i + 1])
  none(string)


func clusterForbidden*(text: string): Option[string] =
  ## facki lo pamoi zunsna remei poi `CLL 3.6` cu to'e curmi ke'a ku'o .a lo pamoi zunsna cimei poi
  ##   `CLL 3.7` cu cusku ke'a gi'e to'e curmi ke'a ku'o ne'i le se ciska .i dunda `none` va'o lo nu
  ##   ro zunsna remei .e ro zunsna cimei cu se curmi .i lo fu'ivla cu nitcu di'u to `CLL 4.7` toi
  ##   .i mupli fa lo nu `lerndjamo` cu vasru `ndj`
  let pair = text.pairForbidden
  if pair.isSome: return pair
  for i in 0 ..< text.len - 2:
    if text[i .. i + 2] in TRIPLES_FORBIDDEN: return some(text[i .. i + 2])
  none(string)


func clusterOpeningForbidden*(text: string): Option[string] =
  ## facki lo zunsna gunma poi krasi le se ciska gi'e vasru su'o zunsna remei poi na ka'e krasi lo
  ##   valsi ja'i `CLL 3.7` .i `CLL 4.7` cu to'e curmi lo nu lo fu'ivla cu se krasi lo vi zunsna
  ##   gunma .i dunda `none` va'o lo nu le se ciska cu se krasi lo karsna .a pa zunsna po'o .a lo
  ##   zunsna gunma poi ro zunsna remei pe ke'a cu ka'e krasi lo valsi
  var finish = 0
  while finish < text.len and text[finish].isConsonant: inc finish
  for i in 0 ..< finish - 1:
    if not isPairInitial(text[i], text[i + 1]): return some(text[0 ..< finish])
  none(string)


func breakup*(text: string): Option[string] =
  ## facki lo valsi poi du zo la .a zo doi gi'e se vasru le se ciska gi'e na se lidne lo zunsna .i
  ##   lo cmene poi vasru le valsi cu se fendi fi lo valsi to `CLL 4.8` toi .i dunda `none` va'o ga
  ##   lo nu ro le valsi cu se lidne lo zunsna gi lo nu le se ciska cu vasru no le re valsi
  for sequence in SEQUENCES_BREAKUP:
    var at = text.find(sequence)
    while at >= 0:
      if at == 0 or not text[at - 1].isConsonant: return some(sequence)
      at = text.find(sequence, at + 1)
  none(string)


