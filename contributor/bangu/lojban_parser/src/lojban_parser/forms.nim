func isPauseNeeded*(prior, next: string): bool =
  ## jdice ja'i lo lerfu po'o lo du'u xu kau lo javni pe `CLL 4.9` cu nitcu lo denpa poi zvati lo
  ##   jbini be le re valsi .i na tcidu lo nu basna .i le remoi javni cu srana lo valsi poi se fanmo
  ##   lo zunsna .i le cimoi javni cu srana lo valsi poi se krasi lo karsna .a `y` to `CLL 4.2` toi
  ##   .i le vomoi javni cu srana lo cmene poi se lidne lo valsi poi na du zo la .a zo lai .a
  ##   zo la'i .a zo doi .i le xamoi javni cu srana lo lerfu cmavo poi se tarmi `Cy` gi'e lidne lo
  ##   valsi poi na se tarmi `Cy` .i ji'a lo denpa poi zvati lo jbini be `y` jo'u lo bavla'i valsi
  ##   cu se nitcu to `CLL 4.2` toi
  # le remoi javni .e le cimoi javni .e `CLL 4.2`
  if prior[^1].isConsonant or next[0] in VOWELS_SYLLABLE: return true
  if next[^1].isConsonant and prior notin CMAVO_BEFORE_CMENE: return true  # le vomoi javni
  prior == "y" or (prior.isLetteral and not next.isLetteral)  # `CLL 4.2` .e le xamoi javni
