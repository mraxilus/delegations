func form*(text: string): Option[Form] =
  ## facki lo rafsi tarmi pe `CLL 4.6` poi le se ciska cu se tarmi ke'a .i dunda `none` va'o lo nu
  ##   le lerfu cu mapti no tarmi
  template c(i: int): bool = text[i].isConsonant
  template v(i: int): bool = text[i].isVowel

  case text.len
  of 3:
    if c(0) and v(1) and c(2): some(Form.Cvc)
    elif c(0) and c(1) and v(2) and isPairInitial(text[0], text[1]): some(Form.Ccv)
    elif c(0) and v(1) and v(2) and text[1 .. 2] in DIPHTHONGS: some(Form.Cvv)
    else: none(Form)
  of 4:
    if c(0) and v(1) and text[2] == '\'' and v(3): some(Form.Cvv)
    elif c(0) and v(1) and c(2) and c(3) and isPairPermissible(text[2], text[3]):
      some(Form.Cvcc)
    elif c(0) and c(1) and v(2) and c(3) and isPairInitial(text[0], text[1]): some(Form.Ccvc)
    else: none(Form)
  of 5:
    if c(0) and v(1) and c(2) and c(3) and v(4) and isPairPermissible(text[2], text[3]):
      some(Form.Cvccv)
    elif c(0) and c(1) and v(2) and c(3) and v(4) and isPairInitial(text[0], text[1]):
      some(Form.Ccvcv)
    else: none(Form)
  else: none(Form)


func isGismu*(text: string): bool =
  ## jdice lo du'u xu kau le se ciska cu se tarmi lo gismu tarmi .i lo gismu tarmi cu du `CVC/CV`
  ##   jo'u `CCVCV` to `CLL 4.4` toi .i no roi retsku lo du'u xu kau lo liste cu vasru le se ciska
  let shape = text.form
  shape.isSome and shape.get in FORMS_GISMU


func isBrivla*(text: string): bool =
  ## jdice lo du'u xu kau le se ciska cu ckaji ro se ckaji be ro brivla be'o poi lo se ciska cu ka'e
  ##   jarco ke'a to `CLL 4.3` toi .i le se ckaji cu du lo ka se fanmo lo karsna kei jo'u lo ka
  ##   vasru lo zunsna remei ne'i le mu lerfu poi krasi .i `y` .e zoi gy. ' .gy. na se kancu
  ##   .i lo nu basna cu cimoi se ckaji .i lo se ciska cu ralte no nu basna .i lo se ciska valsi poi
  ##     vasru no barda lerfu cu se basna lo slaka poi lidne lo romoi
  if text.len == 0 or not text[^1].isVowel: return false
  var letters: string
  for character in text:
    if character notin {'y', '\''}: letters.add character
    if letters.len == 5: break
  for i in 0 ..< letters.len - 1:
    if letters[i].isConsonant and letters[i + 1].isConsonant: return true
  false


func nuclei*(text: string, kind: Kind, breaks: openArray[int] = []): seq[Slice[int]] =
  ## facki lo midju be ro slaka be lo valsi poi `kind` cu klesi ke'a .i lo midju cu du pa karsna
  ##   po'o .a `y` po'o .a pa karsna remei noi ro roi zvati pa slaka po'o to `CLL 3.4` toi .i lo
  ##   karsna remei cu se facki ta'i lo nu klama fi lo zunle fe lo pritu to `CLL 3.5` toi .i lo
  ##   sakli karsna cu karsna remei ne'i ro stuzi be lo fu'ivla .e lo cmene .i ku'i ne'i lo cmavo lo
  ##   sakli karsna cu karsna remei va'o lo nu pamoi kei po'o .i `iy` .e `uy` cu karsna remei ne'i
  ##   lo cmene po'o to `CLL 3.4` .e `CLL 4.2` toi
  ##   .i va'o lo nu slaka bu cu lidne lo lerfu pe `breaks` kei le re karsna cu se fendi fi re slaka
  ##     to `CLL 3.5` toi
  var at = 0
  while at < text.len:
    if text[at] notin VOWELS_SYLLABLE:
      inc at
      continue
    let
      pair = text[at .. min(at + 1, text.high)]
      is_glide =
        (pair in DIPHTHONGS_CMAVO and (kind in KINDS_GLIDE or at == 0)) or
        (pair in DIPHTHONGS_NAME and kind == Kind.Cmene)
      is_parted = at + 1 in breaks
      size = (if (pair in DIPHTHONGS or is_glide) and not is_parted: 2 else: 1)
    result.add at .. at + size - 1
    at += size


func syllables*(text: string, kind: Kind): int =
  ## kancu lo slaka be lo valsi poi `kind` cu klesi ke'a .i ro midju cu zbasu pa slaka .i `y` cu se
  ##   kancu ji'a to `CLL 3.4` toi
  text.nuclei(kind).len


func isCmavo*(text: string): bool =
  ## jdice lo du'u xu kau le se ciska cu du pa cmavo ja'i lo tarmi pe `CLL 4.2` .i le tarmi cu du
  ##   `V` .a `VV` .a `CV` .a `CVV` .a lo porsi be su'o ci karsna be'o poi `CLL 4.2` cu ralte ke'a
  ##   mu'i lo nu cipra .i ja le se ciska cu du lo lerfu cmavo po'u `Cy` .a `y` po'o .a `y'y` to
  ##   `CLL 4.2` .e `CLL 17.2` toi
  ##   .i `VV` cu du pa karsna remei .a `V'V` to le remoi javni pe `CLL 4.1` toi .i ne'i lo cmavo
  ##     poi lo karsna cu krasi ke'a ku'o le pamoi karsna remei cu ka'e du ji'a pa le pano sakli
  ##     karsna poi `CLL 4.2` cu jmina ke'a .i zoi gy. ' .gy. cu lidne ro karsna poi se lidne le
  ##     pamoi karsna remei
  ##   .i lo denpa poi lidne lo karsna cu na se ciska vi .i denpa bu noi ciska le denpa cu se tcidu
  ##     lo tcidu be lo porsi be lo valsi to `CLL 3.3` toi
  let
    start = (if text.len > 0 and text[0].isConsonant: 1 else: 0)
    rest = text[start .. ^1]
  if rest == "y": return true
  if rest == "y'y": return start == 0
  var at = 0
  while at < rest.len:
    if not rest[at].isVowel: return false
    let pair = rest[at .. min(at + 1, rest.high)]
    if pair in DIPHTHONGS or (at == 0 and start == 0 and pair in DIPHTHONGS_CMAVO): at += 2
    else: inc at
    if at == rest.len: return true
    if rest[at] != '\'': return false
    inc at
  false


func splitCompound*(text: string): seq[string] =
  ## fendi le cmavo gunma fi ro cmavo pe le cmavo gunma ja'i `CLL 4.2` .i dunda lo kunti va'o lo nu
  ##   su'o pagbu cu na cmavo ja'i `CLL 4.2` .i pa cmavo cu se fendi fi vo'a
  ##   .i ro zunsna cu krasi lo cnino pagbu ki'u lo nu lo cmavo cu vasru su'e pa zunsna noi pamoi .i
  ##     ji'a ro lerfu po'u denpa bu cu fanmo lo pagbu .i denpa bu cu sinxa lo denpa poi lidne lo
  ##     cmavo poi lo karsna cu krasi ke'a to `CLL 3.3` toi
  var piece = ""
  for letter in text:
    if letter == '.' or (letter.isConsonant and piece.len > 0):
      if piece.len > 0: result.add piece
      piece = ""
      if letter == '.': continue
    piece.add letter
  if piece.len > 0: result.add piece
  for one in result:
    if not one.isCmavo: return @[]



