func isPauseNeeded(prior, next: Occurrence): bool =
  ## jdice lo du'u lo javni pe `CLL 4.9` nitcu lo denpa poi zvati lo jbini be le re valsi
  ##   .i le javni cu du le mumoi javni .e lo javni poi jdice fi lo lerfu to `forms.nim` toi
  ##   .i le mumoi javni cu srana lo romoi slaka poi se basna gi'e lidne lo brivla .a lo pamoi slaka
  ##       poi se basna to `CLL 4.2` toi
  if isPauseNeeded(prior.text, next.text): return true
  if prior.stress != some(prior.text.nuclei(prior.reading.kind, prior.breaks).high): return false
  next.reading.kind in KINDS_BRIVLA or next.stress == some(0)  # le mumoi javni to `CLL 4.2` toi


func isPauseNeededFirst(word: Occurrence): bool =
  ## jdice lo du'u lo javni pe `CLL 4.9` nitcu lo denpa poi lidne lo valsi poi krasi le porsi
  ##   .i le javni cu du le cimoi javni .a le vomoi javni
  ##   .i le cimoi javni cu srana lo valsi poi selkra lo karsna .a `y` to `CLL 4.2` toi
  ##   .i le vomoi javni cu srana lo cmene
  word.text[0] in VOWELS_NUCLEUS or word.reading.kind == Kind.Cmene


func isStretchSyllabic(text: string, at, start, finish, step: int): bool =
  ## jdice lo du'u lo pagbu be le valsi cu vasru lo karsna .a `y` .a lo zunsna poi ka'e slaka to
  ##     `CLL 3.4` toi
  ##   .i le pagbu cu cfari bu'u slaka bu pe `at` gi'e selfa'a `step`
  ##   .i le pagbu cu selfa'o slaka bu .a zoi gy. ' .gy. .a lo korbi be le valsi
  var i = at + step
  while i >= start and i < finish and text[i] notin {',', '\''}:
    if text[i].toLowerAscii in VOWELS_NUCLEUS + CONSONANTS_SYLLABIC: return true
    i += step
  false


func refusalMarks(text: string, start, finish: int): Option[ReadingStream] =
  ## facki lo pamoi lerfu poi no javni cu curmi ke'a ne'i le selci'avla
  ##   .i le lerfu ka'e du slaka bu
  ##   .i dunda lo nu to'e curmi bu'u le stuzi be le lerfu
  for at in start ..< finish:
    let symbol = text[at]
    if symbol in tanru.LETTERS or symbol in CAPITALS: continue
    if symbol != ',': return some(refuse(Refusal.Letter, at, text.character(at)))  # `CLL 3.1`
    let is_syllabic = text.isStretchSyllabic(at, start, finish, -1) and
        text.isStretchSyllabic(at, start, finish, 1)
    # ja'i `CLL 3.3` slaka bu cu fendi lo slaka
    if not is_syllabic: return some(refuse(Refusal.Comma, at))
  none(ReadingStream)


func toSpelling(text: string, start, finish: int): Spelling =
  ## vimcu lo sinxa le selci'avla
  ##   .i ro brale'u cu binxo lo cmale'u
  ##   .i ro slaka bu cu selvi'u
  for at in start ..< finish:
    if text[at] == ',':
      result.breaks.add result.letters.len
      result.commas.add at
      continue
    if text[at] in CAPITALS: result.capitals.add result.letters.len
    result.letters.add text[at].toLowerAscii
    result.places.add at


func nucleusStressed(word: string, kind: Kind, capitals, breaks: openArray[int]): Option[int] =
  ## facki le slaka karsna poi lo brale'u cu basna ke'a
  ##   .i dunda no da va'o lo nu `CLL 3.9` na curmi le nu basna
  ##   .i mupli fa lo nu lo lerfu .a slaka bu cu fendi le brale'u
  ##   .i ja le brale'u cu pencu no slaka karsna .a su'o re slaka karsna
  ##   .i ja le brale'u cu zvati `y`
  ##   .i ja le brale'u na zvati le slaka poi lidne le romoi slaka pe lo brivla
  ##   .i `y` na se kancu
  ##   .i `capitals` vasru su'o pa namcu
  ##   .i `capitals` .e `breaks` sinxa lo stuzi be lo lerfu pe `word`
  let (first, last) = (capitals[0], capitals[^1])
  if last - first + 1 != capitals.len: return  # ja'i `CLL 3.9` pa slaka po'o cu barda
  for b in breaks:
    # ja'i `CLL 3.3` slaka bu cu fendi lo slaka ne'i le porsi be lo brale'u
    if first < b and b <= last: return
  let spans = word.nuclei(kind, breaks)
  var touched: seq[int]
  for i, nucleus in spans:
    if nucleus.b >= first and nucleus.a <= last: touched.add i
  # ja'i `CLL 3.9` `y` no roi se basna
  if touched.len != 1 or word[spans[touched[0]].a] == 'y': return
  if kind in KINDS_BRIVLA:
    var counted: seq[int]
    for i, nucleus in spans:
      if word[nucleus.a] != 'y': counted.add i
    # ja'i `CLL 3.9` lo brivla cu basna le slaka poi lidne le romoi slaka
    #   .i lo brivla cu vasru su'o re slaka to `CLL 4.3` toi
    if touched[0] != counted[^2]: return
  some(touched[0])


