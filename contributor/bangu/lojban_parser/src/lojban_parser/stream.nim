  ## tcidu pa valsi fi lo lerfu pe `span`
  ##   .i le valsi cu ponse lo nu basna poi le brale'u cu sinxa ke'a
  ##   .i dunda no da va'o lo nu no valsi cu se tcidu kei .a lo nu le brale'u cu na mapti lo javni
  ##       pe `CLL 3.9`
  ##   .i va'o lo nu `is_parting` jetnu kei slaka bu cu fendi lo slaka
  ##   .i va'o lo drata slaka bu cu jdice no valsi
  ##   .i lo denpa na seljdi
  let
    piece = spelling.letters[span]
    reading = piece.readWord
  if not reading.is_word: return

  # tcidu lo nu basna poi lo brale'u cu sinxa ke'a
  #   .i slaka bu poi zvati lo brale'u cu fendi le porsi be lo brale'u
  #   .i to'e curmi lo nu basna poi `CLL 3.9` na curmi ke'a
  var capitals, breaks: seq[int]
  for b in spelling.breaks:
    if is_parting and b > span.a and b <= span.b: breaks.add b - span.a
  for c in spelling.capitals:
    if c in span: capitals.add c - span.a
  var stress = none(int)
  if capitals.len > 0:
    stress = piece.nucleusStressed(reading.kind, capitals, breaks)
    if stress.isNone: return

  # lo selci'avla poi vasru lo brale'u cu sinxa ro nu basna sepi'o le brale'u
  #   .i lo selci'avla poi vasru no brale'u cu basna le slaka po'o poi lidne le romoi slaka pe le se
  #       ciska valsi to `D3 a` bu'u `#811` toi
  #   .i se ki'u bo lo brivla cu vasru lo brale'u gi'a se lidne no karsna poi se kancu mu'i lo nu
  #       basna ne'i le selci'avla
  if reading.kind in KINDS_BRIVLA:
    if spelling.capitals.len > 0 and stress.isNone: return
    if spelling.capitals.len == 0 and spelling.letters[span.b + 1 .. ^1].anyIt(it in VOWELS): return
  some(Occurrence(
    start: spelling.places[span.a], finish: spelling.places[span.b] + 1, text: piece,
    stress: stress, breaks: breaks, reading: reading,
  ))


func splitWritten(spelling: Spelling, is_parting: bool): Split =
  ## fendi le selci'avla fi lo valsi
  ##   .i le ve fendi cu nitcu lo mecraide'a poi lo javni cu nitcu ke'a zi'e poi le selci'a na ciska
  ##       ke'a to `CLL 3.3` .e `CLL 4.9` toi
  ##   .i no denpa cu zvati lo stuzi be slaka bu
  ##   .i kancu lo ve fendi poi nitcu lo mecraide'a
  ##   .i li re cu sinxa li su'o re
  ##   .i va'o lo nu `is_parting` jetnu kei slaka bu cu fendi lo slaka
  ##   .i `words[j][i]` vasru lo valsi pe lo lerfu po'u `j ..< i`
  ##   .i `scores[j][i]` vasru lo ve fendi poi le valsi cu fanmo ke'a
  let n = spelling.letters.len
  var
    words = newSeqWith(n + 1, newSeq[Option[Occurrence]](n + 1))
    scores = newSeqWith(n + 1, newSeq[Option[Score]](n + 1))

  # dunda lo namcu ro valsi ja'i lo mecrailai be lo denpa pe lo ve fendi poi le valsi cu fanmo ke'a
  #   .i kancu lo nu mintu
  for i in 1 .. n:
    for j in 0 ..< i:
      let word = spelling.occurrenceWritten(j .. i - 1, is_parting)
      if word.isNone: continue
      # lo cmene cu romoi
      if word.get.reading.kind == Kind.Cmene and i < n: continue  # `CLL 4.8`
      words[j][i] = word
      if j == 0:
        scores[j][i] = some(Score(pauses: 0, ties: 1))
        continue
      let is_comma = j in spelling.breaks
      for k in 0 ..< j:
        if scores[k][j].isNone: continue
        let is_needed = isPauseNeeded(words[k][j].get, word.get)
        # ja'i `CLL 3.3` slaka bu cu sinxa zoi gy. no pause between .gy. bu'u lo jbini be lo slaka
        if is_needed and is_comma: continue
        let
          score = scores[k][j].get
          pauses = score.pauses + ord(is_needed)
        if scores[j][i].isNone or pauses < scores[j][i].get.pauses:
          scores[j][i] = some(Score(pauses: pauses, ties: score.ties, befores: @[k]))
        elif pauses == scores[j][i].get.pauses:
          scores[j][i].get.ties = min(2, scores[j][i].get.ties + score.ties)
          scores[j][i].get.befores.add k

  # cuxna lo mecrailai be lo denpa pe lo valsi poi fanmo le se ciska valsi
  #   .i kancu lo nu mintu
  var lasts: seq[int]
  for j in 1 ..< n:
    if scores[j][n].isNone: continue
    let score = scores[j][n].get
    if lasts.len == 0 or score.pauses < scores[lasts[0]][n].get.pauses:
      lasts = @[j]
      result.count = score.ties
    elif score.pauses == scores[lasts[0]][n].get.pauses:
      lasts.add j
      result.count = min(2, result.count + score.ties)

  # tcidu su'e re ve fendi poi nitcu lo mecraide'a
  #   .i le nu tcidu cu cfari bu'u le romoi valsi gi'e ca'o klama ro valsi poi lidne
  var paths = lasts.mapIt(@[(it, n)])
  while paths.len > 0 and result.splits.len < 2:
    let
      path = paths.pop
      (start, finish) = path[^1]
    if start == 0:
      result.splits.add path.reversed.mapIt(words[it[0]][it[1]].get)
      continue
    for before in scores[start][finish].get.befores.reversed:
      paths.add path & (before, start)


func splitChosen(spelling: Spelling, is_parting: bool): Split =
  ## cuxna lo valsi pe le selci'avla
  ##   .i va'o lo nu le lerfu cu se tcidu ta'i pa mulvla kei cuxna pa valsi
  ##   .i va'o lo datcu'a lo ve fendi poi nitcu lo mecraide'a
  ##   .i va'o lo nu `is_parting` jetnu kei slaka bu cu fendi lo slaka
  let whole = spelling.occurrenceWritten(0 .. spelling.letters.high, is_parting)
  if whole.isSome: return Split(splits: @[@[whole.get]], count: 1)
  spelling.splitWritten(is_parting)


func refusalWritten(spelling: Spelling, start: int): ReadingStream =
  ## to'e curmi lo selci'avla poi se fendi fi no valsi
  ##   .i le nu to'e curmi cu zvati le stuzi po'u `start`
  ##   .i va'o lo nu lo valsi poi le genturfa'i cu tcidu ke'a fi le lerfu cu nitcu lo denpa kei le
  ##       nu to'e curmi cu zvati le pamoi lerfu po'u slaka bu poi zvati le stuzi be le denpa
  ##   .i ki'u bo slaka bu cu sinxa no denpa to `CLL 3.3` toi
  ##   .i va'o lo drata le genturfa'i cu to'e curmi ta'i lo nu `readWord` to'e curmi le lerfu
  ##   .i va'o lo drata le nu to'e curmi cu zvati le pamoi barda lerfu noi na mapti lo javni pe
  ##       `CLL 3.9`
  ##   .i lo lerfu poi se fendi fi lo cmavo cu se fendi vi ji'a
  ##   .i se ki'u bo slaka bu .a lo barda lerfu po'o cu fanta lo nu le lerfu cu se tcidu
  var bare = spelling
  (bare.breaks, bare.commas) = (newSeq[int](), newSeq[int]())
  let split = bare.splitChosen(is_parting = false)
  if split.count > 0:
    var lo = 0
    for i, word in split.splits[0]:
      let k = spelling.breaks.find(lo)
      if i > 0 and k >= 0 and isPauseNeeded(split.splits[0][i - 1], word):
        # ja'i `CLL 3.3` slaka bu na ka'e du lo denpa
        #   .i `CLL 3.3` cusku zoi gy. cannot be .gy.
        return refuse(Refusal.Comma, spelling.commas[k])
      lo += word.text.len
  let whole = spelling.letters.readWord
  if not whole.is_word and whole.refusal != Refusal.Stream:
    return refuse(whole.refusal, start, whole.detail)
  doAssert spelling.capitals.len > 0, "Written word whose letters read should break 3.9 by capital."
  refuse(Refusal.Stress, spelling.places[spelling.capitals[0]])  # `CLL 3.9`


func refusalCommas(spelling: Spelling, words: openArray[Occurrence]): Option[ReadingStream] =
  ## facki lo pamoi lerfu po'u slaka bu poi na mapti lo javni ja'i lo valsi poi le selci'avla cu
  ##     vasru ke'a
  ##   .i dunda lo nu to'e curmi bu'u le stuzi be le lerfu
  ##   .i le lerfu cu zvati lo karsna gunma pe pa cmavo .a pa gismu .a pa lujvo to `CLL 3.4` toi
  ##   .i ja le lerfu cu zvati lo stuzi poi lo denpa cu bigzva ke'a ne'i lo jbini be re valsi
  ##   .i ki'u bo slaka bu cu selski `CLL 3.3` fo zoi gy. cannot be pronounced as pause .gy.
  var
    lo = 0
    k = 0
  for i, word in words:
    let hi = lo + word.text.len
    while k < spelling.breaks.len and spelling.breaks[k] < hi:
      let
        b = spelling.breaks[k] - lo
        is_broken =
          if b == 0: isPauseNeeded(words[i - 1], word)
          else: word.text[b - 1] in VOWELS_NUCLEUS and word.text[b] in VOWELS_NUCLEUS and
              word.reading.kind in KINDS_DIPHTHONG
      if is_broken: return some(refuse(Refusal.Comma, spelling.commas[k]))
      inc k
    lo = hi
  none(ReadingStream)


func isForeign(word: Occurrence): bool =
  ## jdice lo du'u le valsi pe le porsi cu vasru lo selci'a poi zo zoi .a zo la'o sitna ke'a
  ##   .i le selci'a na lojbo to le zemoi javni pe `CLL 4.9` toi
  not word.reading.is_word and word.reading.refusal == Refusal.Foreign


func pauseBefore(occurrences: openArray[Occurrence], word: Occurrence, is_period: bool): Pause =
  ## cusku lo denpa poi lidne lo valsi poi se lidne `occurrences`
  ##   .i denpa bu cu sinxa le denpa
  ##   .i ja lo javni cu nitcu le denpa
  ##   .i lo selci'a poi se sitna gi'e na lojbo cu se lidne pa denpa gi'e lidne pa denpa to le zemoi
  ##       javni pe `CLL 4.9` toi
  if is_period: return Pause.Written
  let is_needed =
    if occurrences.len == 0: word.isPauseNeededFirst
    elif occurrences[^1].isForeign or word.isForeign: true
    else: isPauseNeeded(occurrences[^1], word)
  if is_needed: Pause.Inferred else: Pause.Absent


func wordsWritten(text: string, start, finish: int): ReadingStream =
  ## tcidu lo valsi pe lo selci'avla pe lo stuzi po'u `start ..< finish`
  ##   .i lo denpa na seljdi
  ##   .i to'e curmi lo pagbu poi no javni cu curmi ke'a
  ##   .i le pagbu cu sinxa ja lerfu ja ve fendi
  let refusal_marks = text.refusalMarks(start, finish)
  if refusal_marks.isSome: return refusal_marks.get

  # cuxna lo valsi poi mapti ro sinxa
  #   .i slaka bu cu fendi lo slaka ta'i lo nu `CLL 3.5` fendi lo karsna sepi'o slaka bu
  #   .i se ki'u bo lo brale'u cu basna lo slaka poi slaka bu cu sinxa ke'a
  #   .i ji'a ja'i `CLL 3.3` no ve fendi cu punji lo denpa lo stuzi be slaka bu
  let
    spelling = text.toSpelling(start, finish)
    split = spelling.splitChosen(is_parting = true)
  if split.count == 0: return spelling.refusalWritten(start)
  if split.count > 1:
    let detail = split.splits.mapIt(it.mapIt(it.text).join(" ")).join(", or ")
    # ja'i `CLL 3.3` le genturfa'i na ka'e facki lo pa ve fendi
    return refuse(Refusal.Split, start, detail)
  let refusal_commas = spelling.refusalCommas(split.splits[0])
  if refusal_commas.isSome: return refusal_commas.get
  ReadingStream(is_read: true, occurrences: split.splits[0])


func quoted(text: string, start: int, delimiter: string): Option[Slice[int]] =
  ## facki lo stuzi be lo selci'a poi se sitna
  ##   .i le selci'a cu cfari bu'u `start` gi'e fanmo pu lo bavla'i se ciska valsi poi ciska
  ##       `delimiter`
  ##   .i lo sinxa poi sruri le selci'a cu selvi'u
  ##   .i dunda no da va'o lo nu no selci'avla poi ciska `delimiter` se lidne to `CLL 19.10` toi
  var at = start
  while at < text.len:
    if text[at] in MARKS_BOUNDARY:
      inc at
      continue
    let first = at
    while at < text.len and text[at] notin MARKS_BOUNDARY: inc at
    if text[first ..< at].toLowerAscii.replace(",", "") != delimiter: continue
    var (a, b) = (start, first - 1)
    while a <= b and text[a] in MARKS_BOUNDARY: inc a
    while b >= a and text[b] in MARKS_BOUNDARY: dec b
    return some(a .. b)
  none(Slice[int])


func readStream*(text: string, is_lohu = false): ReadingStream =
  ## tcidu lo valsi pe le selci'a ja'i lo javni pe `CLL` po'o
  ##   .i ro valsi cu ponse lo denpa poi lidne le valsi ku'o .e lo nu basna poi le selci'a cu sinxa
  ##       ke'a
  ##   .i to'e curmi bu'u le pamoi pagbu poi no javni cu curmi ke'a
  ##   .i le pagbu cu valsi ja sinxa
  ##   .i cusku le stuzi be le pagbu
  ##   .i va'o lo nu `is_lohu` jetnu kei le selci'a cu cfari ne'i lo valsi poi zo lo'u sitna ke'a
  ##   .i lo mivyselci'a cu tcidu le selci'a ta'i di'u ba zo lo'u noi ca'o denpa
  ##   .i lo selci'a poi zo zoi .a zo la'o sitna ke'a mulno gi'e du pa valsi pe le porsi gi'e na
  ##       selga'i
  ##   .i lo nu sitna poi zo zo .a zo lo'u zbasu ke'a sitna lo valsi
  ##   .i zo lo'u sitna lo valsi poi lidne zo le'u
  ##   .i se ki'u bo lo cmavo poi se sitna cu galfi no da to `CLL 19.9` toi
  ##   .i le porsi cu sisti ba zo fa'o poi no nu sitna cu vasru ke'a
  ##   .i zo fa'o fanmo lo selci'a poi ka'e se tcidu to `CLL 21.1` toi
  var
    occurrences: seq[Occurrence]
    is_period, is_quoting = false
    is_lohu = is_lohu  # lo valsi poi zo lo'u sitna ke'a to le valsi cu lidne zo le'u toi
    # lo nu sitna poi le koivla pe ke'a bavla'i
    #   .i lo koivla poi fanmo le selci'a
    zoi, closing = none(int)
    at = 0
  while at < text.len:
    # klama pa'o lo sinxa poi zvati lo jbini be lo valsi
    #   .i ralte lo du'u denpa bu cu zvati
    if text[at] in MARKS_BOUNDARY:
      is_period = is_period or text[at] == '.'
      inc at
      continue

    # lebna lo selci'avla poi fanmo pu lo bavla'i sinxa poi zvati lo jbini be lo valsi
    #   .i tcidu lo valsi pe le selci'avla
    let start = at
    while at < text.len and text[at] notin MARKS_BOUNDARY: inc at
    let written = text.wordsWritten(start, at)
    if not written.is_read: return written
    let words = written.occurrences

    # tcidu le koivla poi fanmo le selci'a poi se sitna
    #   .i le selci'avla cu vasru pa valsi po'o
    #   .i le valsi cu selci'a ta'i le korbi valsi to `CLL 19.10` toi
    if closing.isSome:
      if words.len != 1 or words[0].text != occurrences[closing.get].text:
        return refuse(Refusal.Quotation, start)
      var occurrence = words[0]
      # le zemoi javni pe `CLL 4.9`
      occurrence.pause = (if is_period: Pause.Written else: Pause.Inferred)
      occurrences.add occurrence
      (closing, is_period) = (none(int), false)
      continue

    # jmina ro valsi
    #   .i ro valsi cu ponse lo denpa poi lidne le valsi
    #   .i jersi lo nu sitna poi le valsi cu krasi ja fanmo ke'a
    for i, word in words:
      var occurrence = word
      occurrence.pause = occurrences.pauseBefore(occurrence, is_period = i == 0 and is_period)
      occurrences.add occurrence

      # lo koivla cu fanmo lo selci'avla pe vo'a
      #   .i le selci'a poi le koivla cu sitna ke'a fanmo pu lo nu le koivla cu rapli se ciska to
      #       `CLL 19.10` toi
      if zoi.isSome:
        if i < words.high: return refuse(Refusal.Quotation, words[i + 1].start)
        let span = text.quoted(at, word.text)
        if span.isNone: return refuse(Refusal.Quotation, occurrences[zoi.get].start, word.text)
        let quotation = text[span.get]
        if word.text in quotation.toLowerAscii:
          # ja'i `CLL 19.10` le koivla cu selski fo zoi gy. not found .gy. ne'i le selci'a
          return refuse(Refusal.Quotation, span.get.a)
        occurrences.add Occurrence(
          start: span.get.a, finish: span.get.b + 1, text: quotation, stress: none(int),
          pause: (if '.' in text[at ..< span.get.a]: Pause.Written else: Pause.Inferred),
          reading: Reading(is_word: false, refusal: Refusal.Foreign),
        )
        (zoi, closing, at) = (none(int), some(occurrences.high - 1), span.get.b + 1)
        break

      # zo zo sitna lo bavla'i valsi
      #   .i zo lo'u sitna lo valsi poi lidne zo le'u
      #   .i ku'i zo le'u poi zo zo sitna ke'a fanmo no da to `CLL 19.9` toi
      if is_quoting:
        is_quoting = false
        continue
      let selmaho = word.reading.selmaho
      if is_lohu:
        if selmaho == some(Selmaho.Zo): is_quoting = true
        elif selmaho == some(Selmaho.Lehu): is_lohu = false
        continue
      if selmaho == some(Selmaho.Zo): is_quoting = true
      elif selmaho == some(Selmaho.Lohu): is_lohu = true
      elif selmaho == some(Selmaho.Zoi): zoi = some(occurrences.high)
      elif selmaho == some(Selmaho.Faho):
        # `CLL 19.15`
        #   .i le selci'a cu fanmo
        return ReadingStream(is_read: true, occurrences: occurrences)
    is_period = false
  # `CLL 19.10`
  #   .i no koivla cu zvati
  if zoi.isSome: return refuse(Refusal.Quotation, occurrences[zoi.get].start)
  ReadingStream(is_read: true, occurrences: occurrences)
