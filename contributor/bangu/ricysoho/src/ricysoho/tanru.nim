func part(piece: Piece): Part =
  ## dunda lo valsi poi le rafsi cu sinxa ke'a va'o lo nu le liste cu dunda pa valsi le rafsi to
  ##     `CLL 4.6` toi
  ##   .i va'o lo drata cu ralte lo lerfu pe le rafsi
  let found =
    case piece.form
    of Form.Cvc, Form.Ccv, Form.Cvv: piece.rafsi.wordRafsi
    of Form.Cvcc, Form.Ccvc:
      let stems = piece.rafsi.wordsStem
      if stems.len == 1: some(stems[0]) else: none(Word)
    of Form.Cvccv, Form.Ccvcv: piece.rafsi.word
  if found.isSome: found.get.toPart else: Part(is_listed: false, letters: piece.rafsi)


func refuse(refusal: Refusal, detail = ""): Reading =
  ## zbasu lo se tcidu poi sinxa lo nu to'e curmi lo selci'a
  Reading(is_word: false, refusal: refusal, detail: detail)


func character*(text: string, at: int): string =
  ## tcidu lo lerfu poi cfari bu'u lo stuzi po'u `at`
  ##   .i le lerfu cu du lo krastu ce'o ro lo minstu poi le krastu cu jarco ke'a ja'i `Table 3-6`
  ##       noi selcme zoi ky. UTF-8 Bit Distribution .ky. zi'e pe `Unicode Standard`
  ##   .i va'o lo nu le krastu cu lidne no minstu kei le lerfu cu du le krasi stuzi po'o
  let size =
    case uint8(text[at])
    of 0xC0'u8..0xDF'u8: 2
    of 0xE0'u8..0xEF'u8: 3
    of 0xF0'u8..0xF7'u8: 4
    else: 1
  var finish = at + 1
  while finish < min(text.len, at + size) and (uint8(text[finish]) and 0xC0) == 0x80: inc finish
  text[at..<finish]


func isPairHeld(text: string): bool =
  ## jdice lo du'u lo selci'a cu vasru su'o zunsna remei
  ##   .i no cmavo cu vasru lo zunsna remei to `CLL 4.2` toi
  for i in 0 ..< text.high:
    if text[i].isConsonant and text[i + 1].isConsonant: return true
  false


func readWhole(text: string, kind: Kind): Reading =
  ## tcidu lo selci'a ta'i pa valsi pe le klesi
  ##   .i le pagbu cu du lo valsi pe lo liste va'o lo nu lo liste cu vasru le selci'a
  ##   .i va'o lo drata le pagbu cu du lo lerfu pe le selci'a
  let
    listed = text.word
    part = if listed.isSome: listed.get.toPart else: Part(is_listed: false, letters: text)
  Reading(
    is_word: true,
    kind: kind,
    tanru: Tanru(parts: @[part]),
    selmaho: (if kind == Kind.Cmavo: text.selmaho else: none(Selmaho)),
  )


func readCmene(text: string): Reading =
  ## tcidu lo selci'a poi selfa'o lo zunsna ku'o ta'i lo cmene ja'i lo javni pe `CLL 4.8`
  ##   .i le cmene cu vasru su'o slaka gi'e vasru no zunsna remei poi na selcru ku'o gi'e na vasru
  ##       zo la .a zo lai .a zo doi vu'o poi no zunsna cu lidne ke'a
  ##   .i lo slaka cu selcmu pa karsna .a `y` .a pa zunsna poi ka'e slaka ku'o mu'u `rl` pe
  ##       `CLL 3.4`
  ##   .i `c` po'o vasru no slaka
  ##   .i se ki'u bo `c` na valsi
  # `CLL 3.4`
  if not text.anyIt(it in VOWELS + {'y', 'l', 'm', 'n', 'r'}): return refuse(Refusal.Shape)
  let pair = text.pairForbidden
  if pair.isSome: return refuse(Refusal.Cluster, pair.get)
  let sequence = text.breakup
  if sequence.isSome: return refuse(Refusal.Breakup, sequence.get)
  readWhole(text, Kind.Cmene)


func refusalFuhivla(text: string): Option[Reading] =
  ## facki lo pamoi javni pe `CLL 4.7` ge'u zi'e poi lo brivla noi na gismu gi'e na lujvo cu na
  ##     mapti ke'a ta'i lo fu'ivla
  ##   .i va'o lo nu le brivla cu mapti ro le javni cu facki no da
  ##   .i le javni cu du lo nu vasru no `y` .e lo nu lo zunsna gunma poi krasi cu se gunma lo zunsna
  ##       remei poi ka'e krasi .e lo nu ro zunsna remei cu selcru .e lo nu na gunma lo valsi .e lo
  ##       cipra po'u zoi gy. slinku'i test .gy.
  if 'y' in text: return some(refuse(Refusal.Shape))  # ja'i `CLL 4.7` no fu'ivla cu vasru `y`
  let opening = text.clusterOpeningForbidden
  # ja'i `CLL 4.7` lo krasi zunsna gunma cu se gunma lo zunsna remei poi ka'e krasi lo valsi
  if opening.isSome: return some(refuse(Refusal.Cluster, opening.get))
  let cluster = text.clusterForbidden
  # ja'i `CLL 4.7` ro zunsna remei cu selcru
  if cluster.isSome: return some(refuse(Refusal.Cluster, cluster.get))
  let words = text.combination
  if words.isSome: return some(refuse(Refusal.Combination, words.get.join(" ")))  # `CLL 4.7`
  let joined = text.slinkuhi
  # ja'i `CLL 4.7` lo cipra po'u zoi gy. slinku'i test .gy.
  if joined.isSome: return some(refuse(Refusal.Slinkuhi, joined.get))
  none(Reading)


func readLujvo(text: string): Reading =
  ## tcidu lo brivla ta'i lo lujvo ja'i lo tarmi pe lo rafsi .e lo lerjo'e pe `CLL 4.11`
  ##   .i le liste cu dunda lo valsi ro lo pagbu poi le liste cu ka'e dunda lo valsi ke'a
  ##   .i va'o lo drata cu tcidu le brivla ta'i lo fu'ivla ja'i lo javni pe `CLL 4.7` gi'a to'e
  ##       curmi le brivla
  ##   .i le nu to'e curmi cu du `Hyphen` va'o lo nu lo lerfu pe le brivla cu se fendi fi lo rafsi
  ##       poi `CLL 4.11` jorne ke'a sepi'o lo datlerjo'e
  let splits = text.splitLujvo
  if splits.len > 0:
    let pieces = splits[0]
    return Reading(is_word: true, kind: Kind.Lujvo, tanru: Tanru(parts: pieces.mapIt(it.part)),
        pieces: pieces)
  let refusal = text.refusalFuhivla
  if refusal.isNone: return readWhole(text, Kind.Fuhivla)
  let segments = text.segmentLujvo
  if segments.len > 0: return refuse(Refusal.Hyphen, joinRafsi(segments[0].mapIt(it.rafsi)))
  refusal.get


func readWord*(text: string): Reading =
  ## tcidu lo selci'a ta'i pa valsi ja'i lo javni pe `CLL` po'o
  ##   .i le valsi cu cmavo ja gismu ja lujvo ja fu'ivla ja cmene
  ##   .iju lo liste cu vasru le valsi
  ##   .i le selci'a cu se tcidu ta'i lo nu selci'a kei ne'i lo raltai
  ##
  ## ni'o lo lerfu poi se to'e curmi cu selsku ta'i lo nu mulno
  ##   .i se ki'u bo le tcila pe lo selci'a pe `UTF-8` stali lo ka me `UTF-8`
  ##   .i lo cipra po'u zoi gy. Character outside letters is named whole, so detail of UTF-8 stays
  ##       UTF-8 .gy. pe `test_tanru.nim` jarco la'e di'u
  if text.len == 0: return refuse(Refusal.Empty)
  for at in 0..<text.len:
    if text[at] in MARKS_STREAM: return refuse(Refusal.Stream, $text[at])
    if text[at] notin LETTERS: return refuse(Refusal.Letter, text.character(at))
  for at in 0..<text.len:
    let is_joining = at > 0 and at < text.high and text[at - 1] in VOWELS_JOINED and
        text[at + 1] in VOWELS_JOINED
    if text[at] == '\'' and not is_joining: return refuse(Refusal.Apostrophe)

  # lo lerfu cu jdice lo klesi
  #   .i `CLL 4.3` jdice lo du'u lo valsi cu cmene gi'a brivla gi'a cmavo
  if text[^1].isConsonant: return readCmene(text)
  if text.isBrivla:
    # ja'i `CLL 4.3` lo nu basna lo slaka poi lidne lo romoi slaka cu nitcu su'o re slaka
    #   .i le slaka cu se kancu ta'i lo fu'ivla ki'u lo nu lo gismu .e lo lujvo cu vasru no sakli
    #       karsna
    if text.syllables(Kind.Fuhivla) < 2: return refuse(Refusal.Shape)
    if text.isGismu: return readWhole(text, Kind.Gismu)
    return readLujvo(text)
  if not text.isPairHeld:
    if text.isCmavo: return readWhole(text, Kind.Cmavo)
    if text.splitCompound.len > 0: return refuse(Refusal.Stream)  # ja'i `CLL 4.2` lo ma'orgunma
    # le valsi cu na cmavo ja'i `CLL 4.2` gi'e na ma'orgunma mu'u `cia` to `CLL 3.4` toi
    return refuse(Refusal.Shape)

  # lo zunsna remei cu se lidne lo mumoi lerfu
  #   .i ja `y` romoi lerfu
  #   .i se ki'u bo le selci'a cu cmima no klesi pe `CLL 4.3` ta'i pa valsi
  #   .i `readStream` fendi le selci'a va'o lo nu le selci'a cu vlagunma mu'u `lonubarda`
  refuse(Refusal.Shape)



