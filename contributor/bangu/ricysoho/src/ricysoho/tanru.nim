func `==`*(a, b: Part): bool =
  ## karbi re pagbu
  ##   .i lo pagbu poi selste cu se karbi ta'i lo valsi
  ##   .i lo datpau cu se karbi ta'i lo lerfu
  ##   .i lo pagbu poi selste cu no roi du lo datpau
  if a.is_listed != b.is_listed: return false
  if a.is_listed: a.word == b.word else: a.letters == b.letters


