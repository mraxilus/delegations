func choices(part: Part, is_final: bool): seq[string] {.used.} =  # selpli `test_tanru.nim`
  ## dunda lo liste be lo rafsi be lo pagbu be'o poi `CLL 4.11 step 1` .e `CLL 4.11 step 2` curmi
  ##     ke'a bu'u lo stuzi be le pagbu
  ##   .i lo cmavo cu ponse lo cmalu rafsi po'o
  ##   .i lo rafsi poi vasru vo lerfu gi'e selpo'e su'o re gismu cu selvi'u va'o lo nu le gismu cu
  ##       ponse su'o datrafsi
  ##   .i lo pagbu poi no liste cu vasru ke'a dunda lo lerfu pe vo'a va'o lo nu lo tarmi be le lerfu
  ##       cu selcru bu'u le stuzi kei gi'a dunda lo rafsi poi vasru vo lerfu ku'o va'o lo nu le
  ##       pagbu cu gismu gi'e mulseltcidu
  ##   .i lo cmavo poi no rafsi cu sinxa ke'a ku'o mu'u zo lo dunda no da
  if not part.is_listed:
    let shape = part.letters.form
    if shape.isNone: return
    if shape.get in FORMS_GISMU:
      return @[(if is_final: part.letters else: part.letters[0 .. 3])]
    let forms_allowed = (if is_final: FORMS_FINAL else: FORMS_SHORT + FORMS_UNREDUCED)
    if shape.get in forms_allowed: result.add part.letters
    return
  let entry = part.word.entry
  if is_final:
    for one in entry.rafsi:
      if one.form.get in {Form.Ccv, Form.Cvv}: result.add one
    if part.word.kind == Kind.Gismu: result.add entry.word
    return
  result = entry.rafsi
  if part.word.kind != Kind.Gismu: return
  let stem = entry.word[0 .. 3]
  if stem.wordsStem.len == 1 or result.len == 0: result.add stem


func searchLowest(options: seq[seq[string]]): seq[string] {.used.} =  # selpli `test_tanru.nim`
  ## cuxna lo rafsi lo tercu'a pe ro stuzi
  ##   .i su'o re stuzi cu zasti
  ##   .i lo porsi be le selcu'a cu ponse lo cmaraina'u ja'i `CLL 4.12`
  ##   .i va'o lo nu lo namcu cu mintu cu cuxna lo pamoi ja'i lo porsi be le tercu'a
  ##
  ## ni'o sisku sepi'o `dynamic programming` bu'u ro stuzi
  ##   .i lo namcu pe `CLL 4.12` sumji lo pagbu pe ro rafsi lo pagbu pe ro terjo'e
  ##   .i lo pagbu pe ro terjo'e cu seljdi le re rafsi poi jibni le terjo'e ku'o .e pa lanci noi
  ##       cusku lo du'u xu kau lo krapoi pe `CLL 4.11 step 5` kalri to `lujvo.nim` toi
  ##   .i se ki'u bo lo temci cu zenba fi lo mintu ca ro nu jmina pa stuzi to la'e di'u selmre ne'i
  ##       lu lo namcu li'u pe `PROVENANCE.md` toi
  ##
  ## ni'o pa liste cu ralte pa namcu pe ro selcu'a bu'u ro stuzi ne'i ro tcini be le porsi
  ##   .i le namcu cu du lo cmaraina'u pe lo rebla
  ##   .i lo nu klama fi le pamoi stuzi cu cuxna lo pamoi se cuxna poi le namcu cu jalge ke'a
  ##   .i se ki'u bo va'o lo nu lo namcu cu mintu kei le pamoi cu selcu'a
  ##   .i lo nu dunda lo namcu ro porsi cu cuxna le pamoi ji'a to `test_tanru.nim` jarco lo du'u le
  ##       re tadji cu dunda lo mintu toi
  ##
  ## ni'o se to'e cuxna fa lo nu dunda lo namcu ro porsi be lo selcu'a
  ##   .i lo te kancu be le porsi cu pilji lo te kancu be lo se cuxna pe ro stuzi
  ##   .i lu lo namcu li'u pe `PROVENANCE.md` cusku lo jdima be ro le re tadji

  func step(
    options: seq[seq[string]]; at, choice, choice_next: int; is_open: bool
  ): tuple[score: int, is_open_next: bool] =
    ## dunda lo namcu pe lo terjo'e poi se lidne lo selcu'a po'u `choice` bu'u `at` ge'u .e lo namcu
    ##     pe lo selcu'a po'u `choice_next` noi se lidne le terjo'e
    ##   .i dunda ji'a lo tcini be le porsi ba le terjo'e
    let
      (before, after) = (options[at][choice], options[at+1][choice_next])
      junction = scoreJunction(is_open, before, after, at, options.len)
    (junction.score + scoreRafsi(after, after.form.get), junction.is_open)

  # ro selcu'a .e ro tcini be le porsi cu terdu'a lo cmaraina'u pe lo rebla
  #   .i lo nu kanji cu cfari bu'u le romoi stuzi
  let count = options.len
  var rest = newSeq[seq[array[bool, int]]](count)
  rest[^1] = newSeq[array[bool, int]](options[^1].len)
  for at in countdown(count - 2, 0):
    rest[at] = newSeq[array[bool, int]](options[at].len)
    for choice in 0..<options[at].len:
      for is_open in [false, true]:
        var lowest = high(int)
        for choice_next in 0..<options[at+1].len:
          let (score, is_open_next) = options.step(at, choice, choice_next, is_open)
          lowest = min(lowest, score + rest[at+1][choice_next][is_open_next])
        rest[at][choice][is_open] = lowest

  # klama fi le pamoi stuzi gi'e cuxna lo pamoi se cuxna poi le cmaraina'u cu jalge ke'a
  var (choice, total) = (0, high(int))
  for candidate in 0..<options[0].len:
    let
      rafsi_first = options[0][candidate]
      value = scoreRafsi(rafsi_first, rafsi_first.form.get) +
          rest[0][candidate][rafsi_first.isRunOpen]
    if value < total: (choice, total) = (candidate, value)
  var is_open = options[0][choice].isRunOpen
  result = @[options[0][choice]]
  for at in 0 ..< count - 1:
    for choice_next in 0..<options[at+1].len:
      let (score, is_open_next) = options.step(at, choice, choice_next, is_open)
      if score + rest[at+1][choice_next][is_open_next] == rest[at][choice][is_open]:
        (choice, is_open) = (choice_next, is_open_next)
        break
    result.add options[at+1][choice]


func `$`*(tanru: Tanru): string =
  ## ciska lo tanru ta'i pa valsi
  ##   .i lo tanru poi ponse pa pagbu po'o cu selci'a ta'i le pagbu
  ##   .i va'o lo drata cu ciska lo jvotai poi lo namcu pe ke'a traji lo ka cmalu ja'i `CLL 4.12`
  ##   .i va'o lo nu lo namcu cu mintu cu cuxna lo pamoi ja'i lo porsi be lo se cuxna to
  ##       `searchLowest` toi
  ##
  ## ni'o va'o lo nu lo tanru cu ponse no jvotai cu ciska lo pagbu be le tanru gi'e punji pa
  ##     calyle'u lo jbini be re pagbu ta'i lo nu `CLL` ciska lo tanru to `CLL 5.1` toi
  ##   .i mupli fa lo tanru poi selfa'o lo cmavo poi ponse no rafsi poi seltai `CCV` .a `CVV`
  if tanru.parts.len == 0: return ""
  if tanru.parts.len == 1: return $tanru.parts[0]
  var options = newSeq[seq[string]](tanru.parts.len)
  for i, part in tanru.parts:
    options[i] = choices(part, is_final = i == tanru.parts.high)
    if options[i].len == 0: return tanru.parts.mapIt($it).join(" ")
  joinRafsi(options.searchLowest)
