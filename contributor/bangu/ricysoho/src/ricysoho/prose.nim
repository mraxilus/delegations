func isWordPlain(piece: Piece, words: openArray[Occurrence], selmaho: set[Selmaho]): bool =
  ## jdice lo du'u xu kau le spisa cu du pa sapyvla poi cmavo be pa cmima be `selmaho`
  piece.is_plain and words[piece.head].isSelmaho(selmaho)


func isJoinable(piece: Piece, words: openArray[Occurrence]): bool =
  ## jdice lo du'u xu kau le spisa cu ka'e lamji zo zei
  ##   .i le spisa cu du pa sapyvla poi na du lo cmavo poi zo zei na galfi ke'a
  ##   .ija le spisa cu du pa porsi pe zo zei
  piece.terminal == some(Selmaho.Zei.toTerminal) or
      (piece.is_plain and not piece.isWordPlain(words, SELMAHO_UNJOINED))


func joined(
    pieces: openArray[Piece], words: openArray[Occurrence], offender: var seq[int]
): Option[seq[Piece]] =
  ## jmina ro valsi poi lidne zo zei ku'o le valsi poi se lidne zo zei ku'o fo pa spisa po'u `ZEI`
  ##   .i lo porsi pe zo zei jmina ro le valsi fo pa spisa to `CLL 4.6` toi
  ##   .i dunda no da va'o lo nu zo zei lamji no valsi poi zo zei ka'e jorne ke'a
  ##   .i ba bo `offender` cmene le me zo zei
  var
    joins: seq[Piece]
    k = 0
  while k < pieces.len:
    let piece = pieces[k]
    if not piece.isWordPlain(words, {Selmaho.Zei}):
      joins.add piece
      inc k
      continue
    let is_joinable = joins.len > 0 and k + 1 < pieces.len and joins[^1].isJoinable(words) and
        pieces[k + 1].is_plain and pieces[k + 1].isJoinable(words)
    if not is_joinable:
      offender = piece.words
      return none(seq[Piece])
    var before = joins.pop
    before.words.add piece.words & pieces[k + 1].words
    (before.terminal, before.is_plain) = (some(Selmaho.Zei.toTerminal), false)
    joins.add before
    k += 2
  some(joins)


func marked(
    pieces: openArray[Piece], words: openArray[Occurrence], offender: var seq[int]
): Option[seq[Piece]] =
  ## dunda ro porsi be lo cmavo be `BAhE` le spisa poi se lidne le porsi
  ##   .i le genvla pe le spisa cu stali to le javni pe li 1100 toi
  ##   .i dunda no da va'o lo nu lo cmavo be `BAhE` cu fanmo le selci'a gi'a lidne zo su poi fanmo
  ##       le selci'a
  ##   .i ba bo `offender` cmene le cmavo
  var
    marks: seq[Piece]
    pending: seq[int]
  for piece in pieces:
    if piece.isWordPlain(words, {Selmaho.Bahe}):
      pending.add piece.words
      continue
    if pending.len > 0 and piece.isWordPlain(words, {Selmaho.Su}): break
    var held = piece
    held.words = pending & held.words
    held.is_plain = held.is_plain and pending.len == 0
    marks.add held
    pending.setLen(0)
  if pending.len > 0:
    offender = pending
    return none(seq[Piece])
  some(marks)


func lettered(
    pieces: openArray[Piece], words: openArray[Occurrence], offender: var seq[int]
): Option[seq[Piece]] =
  ## zbasu pa lervla fi le valsi poi lidne su'o pa me zo bu
  ##   .i le lervla cu du pa spisa po'u `BU` to `CLL 17.4` toi
  ##   .i dunda no da va'o lo nu zo bu se lidne no valsi gi'a se lidne lo cmavo poi zo bu na galfi
  ##       ke'a
  ##   .i ba bo `offender` cmene le me zo bu
  var letters: seq[Piece]
  for piece in pieces:
    if not piece.isWordPlain(words, {Selmaho.Bu}):
      letters.add piece
      continue
    let is_lettered = letters.len > 0 and
        (letters[^1].terminal == some(Selmaho.Bu.toTerminal) or
          (letters[^1].is_plain and not letters[^1].isWordPlain(words, SELMAHO_UNLETTERED)))
    if not is_lettered:
      offender = piece.words
      return none(seq[Piece])
    letters[^1].words.add piece.words
    (letters[^1].terminal, letters[^1].is_plain) = (some(Selmaho.Bu.toTerminal), false)
  some(letters)


func indicated(pieces: openArray[Piece], words: openArray[Occurrence]): seq[Piece] =
  ## dunda ro cnivla le spisa poi lidne le cnivla
  ##   .i zo nai poi se lidne lo cmavo be `UI` .a `CAI` cu kansa le cmavo to `CLL 13.9` .e
  ##       `CLL 19.16` toi
  ##
  ## ni'o lo cnivla poi krasi le selci'a cu stali ta'i lo spisa pe vo'a
  ##   .i le javni pe li 0 cu tcidu le spisa
  ##   .i lo cnivla poi se lidne zo su stali ta'i lo spisa pe vo'a ji'a
  ##   .i zo su krasi lo selci'a
  var
    is_opening = true
    k = 0
  while k < pieces.len:
    let piece = pieces[k]
    if is_opening or not piece.isWordPlain(words, SELMAHO_INDICATORS):
      is_opening = piece.isWordPlain(words, {Selmaho.Su}) or
          (is_opening and piece.isWordPlain(words, SELMAHO_INDICATORS + {Selmaho.Nai}))
      result.add piece
      inc k
      continue
    result[^1].words.add piece.words
    let is_negated = piece.isWordPlain(words, {Selmaho.Ui, Selmaho.Cai}) and k + 1 < pieces.len and
        pieces[k + 1].isWordPlain(words, {Selmaho.Nai})
    if is_negated: result[^1].words.add pieces[k + 1].words
    result[^1].is_plain = false
    k += (if is_negated: 2 else: 1)



