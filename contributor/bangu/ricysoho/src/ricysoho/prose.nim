func isClosingLohu*(words: openArray[Occurrence]): bool =
  ## jdice lo du'u xu kau le valsi cu vasru zo le'u poi no zo zo sitna ke'a
  ##   .i le me zo le'u cu fanmo lo me zo lo'u me'u poi lidne le valsi
  ##   .i ta'i di'u le porsi be lo valsi cu tcidu lo valsi poi zo lo'u sitna ke'a to `CLL 19.9` toi
  var is_quoting = false
  for k in 0 ..< words.len:
    template word: untyped = words[k]
      ## lo datcme be le valsi
      ##   .i `let` zbasu lo fukpi be le valsi
    if not word.reading.is_word: continue
    if is_quoting:
      is_quoting = false
      continue
    if word.isSelmaho({Selmaho.Zo}): is_quoting = true
    elif word.isSelmaho({Selmaho.Lehu}): return true
  false


func toRoles(words: openArray[Occurrence], is_lohu = false): seq[Role] =
  ## dunda le pagbu poi ro valsi cu cpacu ke'a ne'i lo nu sitna
  ##   .i zo zo sitna le bavla'i valsi
  ##   .i zo lo'u sitna lo valsi poi lidne zo le'u poi no zo zo sitna ke'a
  ##   .i zo zoi sitna le koivla pe vo'a ge'u .e le se sitna .e le koivla ta'i lo nu `readStream`
  ##       ralte le valsi
  ##
  ## ni'o zo zo poi fanmo le selci'a cu sitna no valsi
  ##   .i `quotations` to'e curmi le me zo zo me'u to `CLL 19.10` toi
  ##   .i va'o lo nu `is_lohu` jetnu kei le valsi cu cfari ne'i lo valsi poi zo lo'u sitna ke'a ta'i
  ##       lo nu `readStream` tcidu le valsi
  result = newSeq[Role](words.len)
  var
    i = 0
    is_lohu = is_lohu  # lo valsi poi zo lo'u sitna ke'a to le valsi cu lidne zo le'u toi
  while i < words.len:
    if words[i].isSelmaho({Selmaho.Zo}):
      result[i] = (if is_lohu: Role.Inner else: Role.Zo)
      if i + 1 < words.len: result[i + 1] = (if is_lohu: Role.Inner else: Role.Quoted)
      i += 2
      continue
    if is_lohu:
      result[i] = (if words[i].isSelmaho({Selmaho.Lehu}): Role.Lehu else: Role.Inner)
      is_lohu = result[i] == Role.Inner
    elif words[i].isSelmaho({Selmaho.Lohu}):
      (result[i], is_lohu) = (Role.Lohu, true)
    elif words[i].isSelmaho({Selmaho.Zoi}) and i + 3 < words.len:
      for k, role in [Role.Zoi, Role.Delimiter, Role.Foreign, Role.Delimiter]: result[i + k] = role
      i += 4
      continue
    inc i


func erased(
    words: openArray[Occurrence], roles: openArray[Role], offender: var seq[int],
    reach: var Reach, as_parting: bool,
): Option[seq[int]] =
  ## ralte lo valsi poi lo nu vimcu cu cliva ke'a ku'o ta'i lo namcu to `CLL 19.13` toi
  ##   .i zo si vimcu le valsi poi lidne zo si
  ##   .i zo sa vimcu ro valsi poi lidne zo sa gi'e se lidne le romoi valsi poi cmima le selma'o be
  ##       le bavla'i valsi
  ##   .i zo sa vimcu ji'a le romoi valsi
  ##   .i va'o lo nu no valsi cu cmima le selma'o kei zo sa vimcu ro valsi poi lidne zo sa
  ##   .i zo su vimcu ro valsi poi lidne zo su
  ##   .i lo cmavo poi lo nu sitna cu vasru ke'a vimcu no da
  ##
  ## ni'o dunda no da va'o lo nu zo si .a zo sa galfi no da
  ##   .i ba bo `offender` cmene le cmavo
  ##   .i `reach` cmene ro me zo sa me'u poi lidne ro me zo su me'u gi'e vimcu ro valsi poi lidne le
  ##       me zo sa
  ##
  ## ni'o va'o lo nu `as_parting` jetnu kei zo su stali ta'i lo valsi poi selra'e
  ##   .i zo su fanmo le selci'a poi lidne ri
  ##   .i se ki'u bo lo nu vimcu poi se lidne zo su klama no valsi poi lidne zo su to lo seljdi pe
  ##       `#859` toi
  reach = Reach()
  var
    kept: seq[int]
    # lo valsi poi selra'e gi'e lidne `floor` lidne zo su noi romoi
    #   .i lo nu vimcu cu klama no le valsi
    floor = 0
  for i, word in words:
    if roles[i] != Role.Plain or not word.isSelmaho({Selmaho.Si, Selmaho.Sa, Selmaho.Su}):
      kept.add i
      continue
    case word.toSelmaho.get
    of Selmaho.Si:
      if kept.len == floor:
        offender = @[i]
        return none(seq[int])
      kept.setLen(kept.len - 1)
    of Selmaho.Sa:
      if i + 1 >= words.len:
        offender = @[i]
        return none(seq[int])
      let
        marker = words[i + 1].reading.toTerminal
        last = toSeq(floor ..< kept.len).filterIt(words[kept[it]].reading.toTerminal == marker)
      if last.len == 0 and floor == 0: reach.markers.add marker
      kept.setLen(if last.len > 0: last[^1] else: floor)
    else:
      if as_parting: kept.add i
      else: kept.setLen(0)
      floor = kept.len
  some(kept)


func quotations(
    words: openArray[Occurrence], roles: openArray[Role], kept: openArray[int],
    offender: var seq[int],
): Option[seq[Piece]] =
  ## fendi lo valsi poi selra'e lo spisa
  ##   .i ro nu sitna cu zvati pa spisa ta'i pa genvla
  ##   .i ro datyvla cu zvati pa spisa pe vo'a
  ##
  ## ni'o dunda no da va'o lo nu lo nu vimcu cu ralte pa pagbu be pa nu sitna
  ##   .i ji'a dunda no da va'o lo nu zo lo'u sitna no valsi to `CLL 19.80` toi
  ##   .i ba bo `offender` cmene lo valsi pe le nu sitna zi'e poi selra'e
  ##   .i lo nu vimcu cu ralte lo pamoi valsi pe le nu sitna
  ##
  ## ni'o va'o lo nu zo le'u na fanmo le nu sitna pe zo lo'u kei `offender` cmene zo lo'u po'o
  ##   .i se ki'u bo lo valsi poi se lidne zo lo'u se tcidu
  ##   .i lo valsi poi se lidne zo zoi poi ponse no koivla cu go'i ji'a
  ##   .i ne'i lo mivyselci'a zo lo'u vasru no valsi pe lo cacra poi se lidne zo lo'u
  var
    pieces: seq[Piece]
    p = 0
  while p < kept.len:
    let i = kept[p]
    case roles[i]
    of Role.Plain:
      pieces.add Piece(words: @[i], head: i, is_plain: true)
      inc p
    of Role.Zo, Role.Zoi:
      let size = (if roles[i] == Role.Zo: 2 else: 4)
      if p + size > kept.len or kept[p + size - 1] != i + size - 1:
        var q = p + 1
        while q < min(kept.len, p + size) and kept[q] == i + q - p: inc q
        offender = kept[p ..< q]
        return none(seq[Piece])
      let terminal = (if roles[i] == Role.Zo: Selmaho.Zo else: Selmaho.Zoi).toTerminal
      pieces.add Piece(words: kept[p ..< p + size], head: i, terminal: some(terminal))
      p += size
    of Role.Lohu:
      var q = p + 1
      while q < kept.len and roles[kept[q]] == Role.Inner and kept[q] == kept[q - 1] + 1: inc q
      let is_whole = q < kept.len and roles[kept[q]] == Role.Lehu and kept[q] == kept[q - 1] + 1
      if not is_whole or q == p + 1:
        offender = (if is_whole: kept[p .. q] else: @[i])
        return none(seq[Piece])
      pieces.add Piece(words: kept[p .. q], head: i, terminal: some(Selmaho.Lohu.toTerminal))
      p = q + 1
    else:
      offender = @[i]
      return none(seq[Piece])
  some(pieces)



