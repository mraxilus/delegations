func writtenAt(text: string, at: int): Slice[int] =
  ## dunda lo stuzi pe le selci'avla poi vasru le stuzi po'u `at`
  ##   .i le stuzi cu du lo porsi be lo stuzi poi no sinxa poi zvati lo jbini be lo valsi cu fendi
  ##       ke'a
  doAssert at < text.len and text[at] notin MARKS_BOUNDARY,
      "Stream should refuse byte of written word; got byte " & $at & "."
  var (a, b) = (at, at)
  while a > 0 and text[a - 1] notin MARKS_BOUNDARY: dec a
  while b + 1 < text.len and text[b + 1] notin MARKS_BOUNDARY: inc b
  a .. b


func remap(node: var Node, indexes: openArray[int], count: int) =
  ## rinka lo nu ro genvla pe le tricu ge'u .e ro stuzi poi le gerna cu sisti bu'u ke'a sinxa lo
  ##     pagbu
  ##   .i le genvla po'u `k` sinxa le pagbu po'u `indexes[k]`
  ##   .i le fanmo be le genvla cu sinxa le fanmo be ro le pagbu
  ##   .i `count` te kancu le pagbu
  if node.is_terminal:
    node.at = indexes[node.at]
    return
  if node.stop.isSome:
    let at = node.stop.get.at
    node.stop.get.at = (if at < indexes.len: indexes[at] else: count)
  for child in node.children.mitems: child.remap(indexes, count)


func addPaths(node: Node, path: var seq[int], wanted: openArray[bool], paths: var seq[seq[int]]) =
  ## dunda lo pluta be ro pezli pe lo pagbu poi `wanted` sinxa ke'a
  ##   .i le pluta cu porsi lo namcu pe lo panzi bu'u ro dizlo
  ##   .i ro pagbu cu ponse pa pluta
  if node.is_terminal:
    if wanted[node.at]: paths[node.at] = path
    return
  for k in 0 ..< node.children.len:
    path.add k
    node.children[k].addPaths(path, wanted, paths)
    path.setLen(path.len - 1)


func insertAt(node: var Node, path: openArray[int], index: int, leaves: openArray[Node]) =
  ## punji `leaves` ne'i lo panzi be le jgena poi `path` pluta ke'a ku'o pu le panzi po'u `index`
  if path.len > 0:
    node.children[path[0]].insertAt(path.toOpenArray(1, path.high), index, leaves)
    return
  node.children.insert(leaves, index)


func placeRefused*(tree: var Node, reads: openArray[bool], span: Slice[int]) =
  ## punji lo pezli pe ro pagbu pe `span` zi'e poi no genvla cu vasru ke'a
  ##   .i `reads` pe le pagbu cu jitfa
  ##   .i le pezli cu zvati lo jgena poi traji lo ka dizlo kei gi'e vasru le re pagbu poi se tcidu
  ##       gi'e sruri le pagbu
  ##   .i le pezli cu zvati lo jbini be le re pagbu
  ##   .i lo pezli poi lidne le pamoi pagbu poi se tcidu cu zvati le krasi be le genja
  ##   .i lo pezli poi se lidne le romoi pagbu poi se tcidu cu zvati le fanmo be le genja
  ##   .i ro porsi be lo smipau be'o poi zvati lo jbini be re pagbu poi se tcidu cu zvati vi ta'i le
  ##       porsi
  ##
  ## ni'o le tricu cu vasru lo pagbu pe `span` zi'e poi se tcidu
  ##   .i `span` du pa selci'a poi zo su fendi ke'a
  ##   .i lo nu jmina lo pagbu be lo selci'a cu punji ro pagbu ta'i di'u ji'a to `merge.nim` toi
  var
    # lo pagbu poi se tcidu gi'e sruri le porsi
    runs: seq[tuple[before, after: Option[int], leaves: seq[Node]]]
    wanted = newSeq[bool](reads.len)
    last = none(int)  # le romoi pagbu poi se tcidu
    is_open = false  # le romoi porsi cu denpa lo pagbu poi se tcidu gi'e se lidne le porsi
  for k in span:
    if reads[k]:
      if is_open:
        (runs[^1].after, wanted[k], is_open) = (some(k), true, false)
      last = some(k)
      continue
    if not is_open:
      runs.add (last, none(int), newSeq[Node]())
      if last.isSome: wanted[last.get] = true
      is_open = true
    runs[^1].leaves.add Node(is_terminal: true, at: k)
  var
    path: seq[int]
    paths = newSeq[seq[int]](reads.len)
  tree.addPaths(path, wanted, paths)

  # le nu cadzu cu cfari bu'u le romoi porsi gi'e klama le krasi
  #   .i se ki'u bo le pluta be ro pagbu poi lidne le porsi cu stali
  for k in countdown(runs.high, 0):
    template run: untyped = runs[k]
      ## lo datcme be le porsi
      ##   .i `let` zbasu lo fukpi be le porsi
    if run.before.isNone or run.after.isNone:
      tree.children.insert(run.leaves, (if run.before.isNone: 0 else: tree.children.len))
      continue
    template a: untyped = paths[run.before.get]
      ## lo datcme be le pluta be le pagbu poi lidne le porsi
    template b: untyped = paths[run.after.get]
      ## lo datcme be le pluta be le pagbu poi se lidne le porsi
    var depth = 0
    # le re pezli cu drata
    #   .i se ki'u bo le re pluta cu sepli pu lo nu pa le re pluta cu fanmo
    while a[depth] == b[depth]: inc depth
    tree.insertAt(a.toOpenArray(0, depth - 1), a[depth] + 1, run.leaves)


func occurrenceEnded*(text: string, first, last: int): Occurrence =
  ## dunda le selci'avla poi vasru le stuzi po'u `first ..< last`
  ##   .i le valsi cu se lidne zo fa'o poi fanmo le selci'a
  ##   .i le valsi cu du pa valsi poi le porsi be lo valsi na tcidu ke'a
  ##   .i le valsi cu ralte le stuzi ta'i lo nu selci'a kei gi'e ralte lo denpa poi denpa bu cu
  ##       ciska ke'a pu le valsi to `CLL 19.15` toi
  var k = first
  while k > 0 and text[k - 1] in MARKS_BOUNDARY: dec k
  Occurrence(
    start: first, finish: last, text: text[first ..< last],
    pause: (if '.' in text[k ..< first]: Pause.Written else: Pause.Absent),
    reading: Reading(is_word: false, refusal: Refusal.Faho),
  )


func readUnits(text: string, is_lohu = false): ReadingParts =
  ## tcidu lo selci'a sepi'o le porsi be lo valsi be'o .e lo javni pe `CLL 19.16` gi'e fendi le
  ##     selci'a lo pagbu ta'i le porsi be lo pamoi valsi
  ##   .i ranji lo nu tcidu ba ro srera
  ##   .i lo valsi poi pa velru'e cu to'e curmi ke'a zvati pa pagbu pe vo'a to `readTextMarked` toi
  ##
  ## ni'o le tricu cu stali lo ka kunti
  ##   .i le se tcidu cu jarco lo nu vimcu .e lo nu sitna poi denpa
  ##   .i lo mivyselci'a cu tcidu di'u ba le pagbu
  ##
  ## ni'o zo su zvati pa pagbu pe vo'a
  ##   .i zo su fanmo le selci'a poi lidne ri to lo seljdi pe `#859` toi
  ##   .i va'o lo nu `is_lohu` jetnu kei le selci'a cu cfari ne'i lo valsi poi zo lo'u sitna ke'a to
  ##       `readStream` toi
  template occurrences: untyped = result.reading.occurrences
    ## lo datcme be lo valsi pe le se tcidu
  template units: untyped = result.reading.units
    ## lo datcme be lo pagbu pe le se tcidu
  result.reading.size = text.len

  # le porsi be lo valsi zo'u galfi ro selci'avla poi le porsi cu to'e curmi ke'a ku'o lo kutle'u
  #   .i le selci'avla cu zvati pa valsi pe vo'a
  var
    blanked = text
    refused: seq[Occurrence]
    stream = blanked.readStream(is_lohu)
  while not stream.is_read:
    let span = blanked.writtenAt(stream.start)
    var k = span.a
    while k > 0 and text[k - 1] in MARKS_BOUNDARY: dec k
    refused.add Occurrence(
      start: span.a, finish: span.b + 1, text: text[span],
      pause: (if '.' in text[k ..< span.a]: Pause.Written else: Pause.Absent),
      reading: Reading(is_word: false, refusal: stream.refusal, detail: stream.detail),
    )
    if stream.refusal == Refusal.Quotation and stream.detail.len > 0:
      result.zois.add (span.a, stream.detail)  # zo zoi denpa lo koivla pe vo'a
    for i in span: blanked[i] = ' '
    stream = blanked.readStream(is_lohu)
  refused = refused.sortedByIt(it.start)

  # lo valsi poi le porsi be lo valsi cu tcidu ke'a ku'o .e lo valsi poi le porsi cu to'e curmi ke'a
  #     ku'o ta'i le porsi be lo stuzi
  #   .i ro valsi poi se to'e curmi cu zvati pa pagbu pe vo'a
  var
    # lo namcu pe ro valsi poi se tcidu ku'o ne'i `occurrences`
    indexes = newSeq[int](stream.occurrences.len)
    r = 0
  template addRefused() =
    ## jmina le bavla'i valsi poi le porsi be lo valsi cu to'e curmi ke'a ku'o .e lo pagbu poi vasru
    ##     le valsi
    units.add Unit(words: @[occurrences.len], is_read: false, refusal: RefusalText.Stream)
    occurrences.add refused[r]
    inc r
  for k in 0 ..< stream.occurrences.len:
    while r < refused.len and refused[r].start < stream.occurrences[k].start: addRefused()
    indexes[k] = occurrences.len
    occurrences.add stream.occurrences[k]
  while r < refused.len: addRefused()

  # lo javni pe `CLL 19.16` zo'u ro girzu be lo valsi poi pa javni cu to'e curmi ke'a cu zvati pa
  #     pagbu
  #   .i le javni cu tcidu lo valsi poi stali
  let
    words = stream.occurrences.toParsable(is_lohu)
    # le pagbu poi ro valsi cu cpacu ke'a ne'i le pamoi nu tcidu
    #   .i le nu tcidu cu kuspe ro valsi
    roles = words.toRoles
  var
    # lo namcu pe ro valsi poi le javni ca'o tcidu ke'a ku'o ne'i `words`
    alive = toSeq(0 ..< words.len)
    pieces: seq[Piece]
    reach: Reach
  while true:
    var
      refusal: RefusalText
      offender: seq[int]
    let grouped = alive.mapIt(words[it]).toPieces(refusal, offender, reach, as_parting = true)
    for marker in reach.markers:
      # lo me zo sa me'u poi ba se to'e curmi cu pu sisku le sinxa
      if marker notin result.markers: result.markers.add marker
    if grouped.isSome:
      pieces = grouped.get
      break
    doAssert offender.len > 0, "Rule refusing words should name them."
    units.add Unit(words: offender.mapIt(indexes[alive[it]]), is_read: false, refusal: refusal)
    for k in countdown(offender.high, 0): alive.delete(offender[k])

  # ro spisa cu selsni pa genvla gi'a zvati pa pagbu poi no genvla cu vasru ke'a
  #   .i le pagbu cu vasru zo su .a lo cmavo poi no liste cu dunda lo selma'o ke'a
  let left = alive.mapIt(words[it])
  for piece in pieces:
    let
      terminal = piece.toTerminal(left)
      held = piece.words.mapIt(indexes[alive[it]])
    if piece.isWordPlain(left, {Selmaho.Su}):
      units.add Unit(words: held, is_read: false, refusal: RefusalText.Su)
      if roles[alive[piece.head]] != Role.Plain: result.quoted.add words[alive[piece.head]].start
    elif terminal.isSome: units.add Unit(words: held, is_read: true, terminal: terminal.get)
    else: units.add Unit(words: held, is_read: false, refusal: RefusalText.Selmaho)

  # lo valsi poi no pagbu cu vasru ke'a zo'u ro porsi be lo valsi poi lo nu vimcu cu vimcu ke'a cu
  #     kansa le cmavo poi vimcu le porsi to `CLL 19.13` toi
  #   .i ba bo lo pagbu cu vasru zo fa'o poi fanmo le selci'a ku'o .e ro selci'avla poi se lidne zo
  #       fa'o zi'e poi le porsi be lo valsi na tcidu ke'a to `CLL 19.15` toi
  var is_helds = newSeq[bool](occurrences.len)  # su'o pagbu cu vasru le valsi
  for k in 0 ..< units.len:
    for w in units[k].words: is_helds[w] = true
  let ending = (if words.len < stream.occurrences.len: occurrences.high else: occurrences.len)
  var w = 0
  while w < ending:
    if is_helds[w]:
      inc w
      continue
    var run: seq[int]
    while w < ending and not is_helds[w]:
      run.add w
      inc w
    units.add Unit(words: run, is_read: false, refusal: RefusalText.Erasure)
  if ending < occurrences.len:
    units.add Unit(words: @[ending], is_read: false, refusal: RefusalText.Faho)
    var at = occurrences[ending].finish
    while at < text.len:
      if text[at] in MARKS_BOUNDARY:
        inc at
        continue
      let first = at
      while at < text.len and text[at] notin MARKS_BOUNDARY: inc at
      units.add Unit(words: @[occurrences.len], is_read: false, refusal: RefusalText.Stream)
      occurrences.add text.occurrenceEnded(first, at)
  units = units.sortedByIt(it.words[0])
  if ending < occurrences.len:
    var u = units.high
    while units[u].words[0] != ending: dec u
    result.faho = some(u)

  # zo lo'u denpa va'o lo nu le porsi be lo valsi cu tcidu le valsi poi zo lo'u sitna ke'a ku'o ta'i
  #     lo nu klama le fanmo be le selci'a
  #   .i lo pagbu poi vasru zo lo'u na vajni
  let roles_stream = words.toRoles(is_lohu)  # le pagbu pe ro valsi ta'i le porsi be lo valsi
  for w in 0 ..< words.len:
    let is_waiting = roles_stream[w] == Role.Lohu and
      not words.toOpenArray(w + 1, words.high).isClosingLohu
    if is_waiting: result.lohus.add words[w].start


func toTexts(units: openArray[Unit]): seq[Slice[int]] =
  ## dunda lo pagbu pe ro selci'a poi zo su fendi ke'a ku'o ta'i le porsi
  ##   .i le pagbu cu lidne ro me zo su me'u gi'a zvati lo jbini be re me zo su me'u gi'a se lidne
  ##       ro me zo su
  ##   .i no selci'a cu vasru zo su
  var first = 0
  for k in 0 ..< units.len:
    if not units[k].is_read and units[k].refusal == RefusalText.Su:
      result.add first ..< k
      first = k + 1
  result.add first ..< units.len


func toTerminals(
    units: openArray[Unit], span: Slice[int]
): tuple[read: seq[int], terminals: seq[Terminal]] =
  ## dunda lo namcu pe ro pagbu pe `span` zi'e poi le gerna cu tcidu ke'a ku'o ta'i le porsi gi'e
  ##     dunda lo genvla pe ro le pagbu
  for k in span:
    if units[k].is_read:
      result.read.add k
      result.terminals.add units[k].terminal


func readTree(reading: ReadingMarked, span: Slice[int], count: int): Node =
  ## tcidu le pagbu po'u `span` pe le se tcidu gi'e zbasu lo tricu poi jarco ro srera
  ##   .i `span` du pa selci'a poi zo su fendi ke'a
  ##   .i ro pagbu poi se to'e curmi cu zvati le stuzi pe vo'a
  ##   .i va'o lo nu le gerna cu sisti bu'u le fanmo be le selci'a kei le stuzi poi le gerna cu
  ##       sisti bu'u ke'a du le pagbu po'u `count`
  let (read, terminals) = reading.units.toTerminals(span)
  result = terminals.readGrammarMarked
  result.remap(read, count)
  if read.len < span.len: result.placeRefused(reading.units.mapIt(it.is_read), span)


func readTextMarked*(text: string): ReadingMarked =
  ## tcidu lo selci'a ta'i lo nu `readText` tcidu kei gi'e ranji lo nu tcidu ba ro srera gi'e jarco
  ##     ro le srera to `#859` toi
  ##   .i lo valsi poi pa velru'e cu to'e curmi ke'a zvati pa pagbu pe vo'a
  ##   .i le gerna cu tcidu lo valsi poi sruri le pagbu
  ##   .i le tricu cu jarco lo stuzi poi le gerna cu sisti bu'u ke'a to `readGrammarMarked` toi
  ##   .i va'o lo nu `readText` tcidu lo selci'a kei le se tcidu cu mintu le se tcidu pe `readText`
  ##
  ## ni'o le porsi be lo valsi zo'u ro selci'avla poi le porsi cu to'e curmi ke'a zvati pa valsi
  ##     ta'i lo nu selci'a
  ##   .i ba bo le porsi cu raptcidu le selci'a ta'i lo nu lo stuzi pe le valsi cu kutle'u
  ##   .i se ki'u bo ro nu to'e curmi cu vasru pa selci'avla
  ##   .i lo javni pe `CLL 19.16` zo'u lo valsi poi pa javni cu to'e curmi ke'a zvati pa pagbu
  ##   .i le javni cu raptcidu lo valsi poi stali
  ##   .i lo selma'o zo'u lo spisa pe lo cmavo poi no liste cu dunda lo selma'o ke'a du pa pagbu poi
  ##       vasru ro valsi pe le spisa
  ##
  ## ni'o le vi genturfa'i cu jdice no nu cikre ja'i `D1 a` pe `#859`
  ##   .i lo drata samtci cu tcidu le tricu gi'e cikre le selci'a
  ##
  ## ni'o zo su fanmo lo selci'a poi lidne ri
  ##   .i le selci'a cu se tcidu ta'i pa mulselci'a
  ##   .i le selci'a poi se lidne zo su go'i ji'a
  ##
  ## ni'o le genja pe le selci'a poi se lidne zo su noi romoi cu vasru le tricu pe ro selci'a poi
  ##     lidne su'o me zo su
  ##   .i ro le tricu cu lidne lo pezli pe zo su
  ##   .i le tricu .e le pezli cu lidne le jgena pe le genja to lo seljdi pe `#859` toi
  ##   .i se ki'u bo le tricu poi `readText` dunda ke'a du le genja ba zo su noi romoi
  ##   .i zo fa'o poi fanmo le selci'a ku'o .e ro selci'avla poi se lidne zo fa'o zvati lo fanmo be
  ##       le genja gi'e se lidne le selci'a
  let parts = text.readUnits
  result = parts.reading
  let
    ending = (if parts.faho.isSome: parts.faho.get else: result.units.len)
    texts = result.units.toOpenArray(0, ending - 1).toTexts
  # le tricu pe ro selci'a poi lidne zo su noi romoi
  #   .i ro le tricu cu lidne lo pezli pe zo su poi se lidne le tricu
  var before: seq[Node]
  for k in 0 ..< texts.high:
    before.add result.readTree(texts[k], texts[k].b + 1)
    before.add Node(is_terminal: true, at: texts[k].b + 1)
  result.tree = result.readTree(texts[^1], ending)
  result.tree.children.insert(before, 0)
  for u in ending ..< result.units.len: result.tree.children.add Node(is_terminal: true, at: u)


func readTextParts*(
    charts: var ChartsKept, text: string, is_live, is_lohu = false
): ReadingParts =
  ## tcidu lo selci'a ta'i lo nu `readTextMarked` tcidu kei gi'e zbasu lo jgena pe ro pagbu poi le
  ##     so'i nu tcidu cu katna ke'a
  ##   .i ro pagbu cu se tcidu ta'i pa mulno se ciska to `readGrammarParts` toi
  ##   .i se ki'u bo ro jufra pe lo mivyselci'a cu selbe'i ca lo nu le jufra cu fanmo
  ##   .i le genja cu vasru le jgena .e ro pagbu poi se to'e curmi gi'e zvati lo jbini be le pagbu
  ##       be le selci'a
  ##   .i `assembleText` zbasu le tricu pe le selci'a
  ##
  ## ni'o lo mivyselci'a poi `is_live` jarco ke'a katna ba lo kravla poi denpa lo famvla pe vo'a to
  ##     lo seljdi pe `#859` toi
  ##   .i ji'a lo mivyselci'a cu tcidu ta'i lo nu cfari ne'i lo valsi poi zo lo'u sitna ke'a kei lo
  ##       selci'a poi se lidne zo lo'u poi denpa to `is_lohu` toi
  ##   .i le porsi be lo valsi cu go'i ji'a
  ##
  ## ni'o zo su fanmo lo selci'a poi lidne ri
  ##   .i le selci'a cu se tcidu ta'i pa mulselci'a
  ##   .i le selci'a poi se lidne zo su go'i ji'a
  ##   .i le pezli pe zo su zvati lo jbini be le pagbu be le re selci'a
  ##
  ## ni'o lo kravla poi denpa gi'e zvati le selci'a poi lidne zo su selfa'o bu'u zo su ta'i lo nu
  ##     selfa'o bu'u lo fanmo be lo selci'a
  ##   .i se ki'u bo lo mivyselci'a cu katna ba lo krasi valsi po'o poi zvati le selci'a poi se
  ##       lidne zo su noi romoi
  ##
  ## ni'o `charts` cu ralte le mulcmi pe le romoi pagbu poi se tcidu to `readGrammarParts` toi
  result = text.readUnits(is_lohu)
  template reading: untyped = result.reading
    ## lo datcme be le se tcidu pe le pagbu
  reading.tree = Node(is_terminal: false, rule: "text", number: 0)
  let
    ending = (if result.faho.isSome: result.faho.get else: reading.units.len)
    texts = reading.units.toOpenArray(0, ending - 1).toTexts
  for k in 0 ..< texts.len:
    let
      is_last = k == texts.high
      (read, terminals) = reading.units.toTerminals(texts[k])
      (parts, open) = charts.readGrammarParts(terminals, is_live and is_last)
    var tree = Node(is_terminal: false, rule: "text", number: 0, children: parts)
    tree.remap(read, if is_last: ending else: texts[k].b + 1)
    if read.len < texts[k].len: tree.placeRefused(reading.units.mapIt(it.is_read), texts[k])
    for child in tree.children.mitems: reading.tree.children.add move(child)
    if is_last: result.open = open.mapIt(read[it])
    else: reading.tree.children.add Node(is_terminal: true, at: texts[k].b + 1)
  for u in ending ..< reading.units.len: reading.tree.children.add Node(is_terminal: true, at: u)


func readTextParts*(text: string, is_live, is_lohu = false): ReadingParts =
  ## tcidu lo selci'a ta'i lo nu `readTextParts` tcidu kei sepi'o lo mulcmi poi cnino
  var charts: ChartsKept
  charts.readTextParts(text, is_live, is_lohu)
