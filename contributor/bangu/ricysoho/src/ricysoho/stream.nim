    ## lo lerfu poi zbasu lo slaka
    ##   .i le mu karsna .e `y` to `CLL 3.4` .e `CLL 3.9` toi
  CONSONANTS_SYLLABIC = {'l', 'm', 'n', 'r'}  ## lo zunsna poi ka'e slaka to `CLL 3.4` toi
  KINDS_BRIVLA = {Kind.Gismu, Kind.Lujvo, Kind.Fuhivla}
    ## lo klesi poi basna le slaka po'o poi lidne le romoi slaka to `CLL 3.9` .e `CLL 4.7` toi
  KINDS_DIPHTHONG = {Kind.Cmavo, Kind.Gismu, Kind.Lujvo}
    ## lo klesi poi re lamji karsna pe ke'a zbasu lo karsna gunma
    ##   .i ki'u la'e di'u slaka bu na ka'e fendi le re karsna to `CLL 3.4` toi


func refuse(refusal: Refusal, start: int, detail = ""): ReadingStream =
  ## zbasu lo se tcidu poi to'e curmi le porsi bu'u le stuzi po'u `start`
  ReadingStream(is_read: false, refusal: refusal, start: start, detail: detail)


func isPauseNeeded(prior, next: Occurrence): bool =
  ## jdice lo du'u lo javni pe `CLL 4.9` nitcu lo denpa poi zvati lo jbini be le re valsi
  ##   .i le javni cu du le mumoi javni .e lo javni poi jdice fi lo lerfu to `forms.nim` toi
  ##   .i le mumoi javni cu srana lo romoi slaka poi se basna gi'e lidne lo brivla .a lo pamoi slaka
  ##       poi se basna to `CLL 4.2` toi
  if isPauseNeeded(prior.text, next.text): return true
  if prior.stress != some(prior.text.nuclei(prior.reading.kind, prior.breaks).high): return false
  next.reading.kind in KINDS_BRIVLA or next.stress == some(0)  # le mumoi javni to `CLL 4.2` toi


func isPauseNeededFirst(word: Occurrence): bool =
  ## jdice lo du'u lo javni pe `CLL 4.9` nitcu lo denpa poi lidne lo valsi poi krasi le porsi
  ##   .i le javni cu du le cimoi javni .a le vomoi javni
  ##   .i le cimoi javni cu srana lo valsi poi selkra lo karsna .a `y` to `CLL 4.2` toi
  ##   .i le vomoi javni cu srana lo cmene
  word.text[0] in VOWELS_NUCLEUS or word.reading.kind == Kind.Cmene


func isStretchSyllabic(text: string, at, start, finish, step: int): bool =
  ## jdice lo du'u lo pagbu be le valsi cu vasru lo karsna .a `y` .a lo zunsna poi ka'e slaka to
  ##     `CLL 3.4` toi
  ##   .i le pagbu cu cfari bu'u slaka bu pe `at` gi'e selfa'a `step` gi'e selfa'o slaka bu .a zoi
  ##       gy. ' .gy. .a lo korbi be le valsi
  var i = at + step
  while i >= start and i < finish and text[i] notin {',', '\''}:
    if text[i].toLowerAscii in VOWELS_NUCLEUS + CONSONANTS_SYLLABIC: return true
    i += step
  false


func refusalMarks(text: string, start, finish: int): Option[ReadingStream] =
  ## facki lo pamoi lerfu poi no javni cu curmi ke'a ne'i le selci'avla
  ##   .i le lerfu ka'e du slaka bu
  ##   .i dunda lo nu to'e curmi bu'u le stuzi be le lerfu
  for at in start ..< finish:
    let symbol = text[at]
    if symbol in tanru.LETTERS or symbol in CAPITALS: continue
    if symbol != ',': return some(refuse(Refusal.Letter, at, text.character(at)))  # `CLL 3.1`
    let is_syllabic = text.isStretchSyllabic(at, start, finish, -1) and
        text.isStretchSyllabic(at, start, finish, 1)
    # ja'i `CLL 3.3` slaka bu cu fendi lo slaka
    if not is_syllabic: return some(refuse(Refusal.Comma, at))
  none(ReadingStream)


func toSpelling(text: string, start, finish: int): Spelling =
  ## vimcu lo sinxa le selci'avla
  ##   .i ro brale'u cu binxo lo cmale'u
  ##   .i ro boi slaka bu cu selvi'u
  for at in start ..< finish:
    if text[at] == ',':
      result.breaks.add result.letters.len
      result.commas.add at
      continue
    if text[at] in CAPITALS: result.capitals.add result.letters.len
    result.letters.add text[at].toLowerAscii
    result.places.add at


func nucleusStressed(word: string, kind: Kind, capitals, breaks: openArray[int]): Option[int] =
  ## facki le slaka karsna poi lo brale'u cu basna ke'a
  ##   .i dunda no da va'o lo nu `CLL 3.9` na curmi le nu basna
  ##   .i mupli fa lo nu lo lerfu .a slaka bu cu fendi le brale'u
  ##   .i ja le brale'u cu pencu no slaka karsna .a su'o re slaka karsna
  ##   .i ja le brale'u cu zvati `y`
  ##   .i ja le brale'u na zvati le slaka poi lidne le romoi slaka pe lo brivla
  ##   .i `y` na se kancu
  ##
  ## ni'o `capitals` vasru su'o pa namcu
  ##   .i `capitals` .e `breaks` sinxa lo stuzi be lo lerfu pe `word`
  let (first, last) = (capitals[0], capitals[^1])
  if last - first + 1 != capitals.len: return  # ja'i `CLL 3.9` pa slaka po'o cu barda
  for b in breaks:
    # ja'i `CLL 3.3` slaka bu cu fendi lo slaka ne'i le porsi be lo brale'u
    if first < b and b <= last: return
  let spans = word.nuclei(kind, breaks)
  var touched: seq[int]
  for i, nucleus in spans:
    if nucleus.b >= first and nucleus.a <= last: touched.add i
  # ja'i `CLL 3.9` `y` no roi se basna
  if touched.len != 1 or word[spans[touched[0]].a] == 'y': return
  if kind in KINDS_BRIVLA:
    var counted: seq[int]
    for i, nucleus in spans:
      if word[nucleus.a] != 'y': counted.add i
    # ja'i `CLL 3.9` lo brivla cu basna le slaka poi lidne le romoi slaka
    #   .i lo brivla cu vasru su'o re slaka to `CLL 4.3` toi
    if touched[0] != counted[^2]: return
  some(touched[0])


func occurrenceWritten(
    spelling: Spelling, span: Slice[int], is_parting = true
): Option[Occurrence] =
  ## tcidu pa valsi fi lo lerfu pe `span`
  ##   .i le valsi cu ponse lo nu basna poi le brale'u cu sinxa ke'a
  ##   .i dunda no da va'o lo nu no valsi cu se tcidu kei .a lo nu le brale'u cu na mapti lo javni
  ##       pe `CLL 3.9`
  ##   .i va'o lo nu `is_parting` jetnu kei slaka bu cu fendi lo slaka
  ##   .i va'o lo drata slaka bu cu jdice no valsi
  ##   .i lo denpa na seljdi
  let
    piece = spelling.letters[span]
    reading = piece.readWord
  if not reading.is_word: return

  # tcidu lo nu basna poi lo brale'u cu sinxa ke'a
  #   .i slaka bu poi zvati lo brale'u cu fendi le porsi be lo brale'u
  #   .i to'e curmi lo nu basna poi `CLL 3.9` na curmi ke'a
  var capitals, breaks: seq[int]
  for b in spelling.breaks:
    if is_parting and b > span.a and b <= span.b: breaks.add b - span.a
  for c in spelling.capitals:
    if c in span: capitals.add c - span.a
  var stress = none(int)
  if capitals.len > 0:
    stress = piece.nucleusStressed(reading.kind, capitals, breaks)
    if stress.isNone: return

  # lo selci'avla poi vasru lo brale'u cu sinxa ro nu basna sepi'o le brale'u
  #   .i lo selci'avla poi vasru no brale'u cu basna le slaka po'o poi lidne le romoi slaka pe le se
  #       ciska valsi to `D3 a` bu'u `#811` toi
  #   .i se ki'u bo lo brivla cu vasru lo brale'u gi'a se lidne no karsna poi se kancu mu'i lo nu
  #       basna ne'i le selci'avla
  if reading.kind in KINDS_BRIVLA:
    if spelling.capitals.len > 0 and stress.isNone: return
    if spelling.capitals.len == 0 and spelling.letters[span.b + 1 .. ^1].anyIt(it in VOWELS): return
  some(Occurrence(
    start: spelling.places[span.a], finish: spelling.places[span.b] + 1, text: piece,
    stress: stress, breaks: breaks, reading: reading,
  ))


func splitWritten(spelling: Spelling, is_parting: bool): Split =
  ## fendi le selci'avla fi lo valsi
  ##   .i le ve fendi cu nitcu lo mecraide'a poi lo javni cu nitcu ke'a zi'e poi le selci'a na ciska
  ##       ke'a to `CLL 3.3` .e `CLL 4.9` toi
  ##   .i no denpa cu zvati lo stuzi be slaka bu
  ##   .i kancu lo ve fendi poi nitcu lo mecraide'a
  ##   .i li 2 cu sinxa li su'o re
  ##   .i va'o lo nu `is_parting` jetnu kei slaka bu cu fendi lo slaka
  ##
  ## ni'o `words[j][i]` vasru lo valsi pe lo lerfu po'u `j ..< i`
  ##   .i `scores[j][i]` vasru lo ve fendi poi le valsi cu fanmo ke'a
  let n = spelling.letters.len
  var
    words = newSeqWith(n + 1, newSeq[Option[Occurrence]](n + 1))
    scores = newSeqWith(n + 1, newSeq[Option[Score]](n + 1))

  # dunda lo namcu ro valsi ja'i lo mecrailai be lo denpa pe lo ve fendi poi le valsi cu fanmo ke'a
  #   .i kancu lo nu mintu
  for i in 1 .. n:
    for j in 0 ..< i:
      let word = spelling.occurrenceWritten(j .. i - 1, is_parting)
      if word.isNone: continue
      # lo cmene cu romoi
      if word.get.reading.kind == Kind.Cmene and i < n: continue  # `CLL 4.8`
      words[j][i] = word
      if j == 0:
        scores[j][i] = some(Score(pauses: 0, ties: 1))
        continue
      let is_comma = j in spelling.breaks
      for k in 0 ..< j:
        if scores[k][j].isNone: continue
        let is_needed = isPauseNeeded(words[k][j].get, word.get)
        # ja'i `CLL 3.3` slaka bu cu sinxa zoi gy. no pause between .gy. bu'u lo jbini be lo slaka
        if is_needed and is_comma: continue
        let
          score = scores[k][j].get
          pauses = score.pauses + ord(is_needed)
        if scores[j][i].isNone or pauses < scores[j][i].get.pauses:
          scores[j][i] = some(Score(pauses: pauses, ties: score.ties, befores: @[k]))
        elif pauses == scores[j][i].get.pauses:
          scores[j][i].get.ties = min(2, scores[j][i].get.ties + score.ties)
          scores[j][i].get.befores.add k

  # cuxna lo mecrailai be lo denpa pe lo valsi poi fanmo le selci'avla
  #   .i kancu lo nu mintu
  var lasts: seq[int]
  for j in 1 ..< n:
    if scores[j][n].isNone: continue
    let score = scores[j][n].get
    if lasts.len == 0 or score.pauses < scores[lasts[0]][n].get.pauses:
      lasts = @[j]
      result.count = score.ties
    elif score.pauses == scores[lasts[0]][n].get.pauses:
      lasts.add j
      result.count = min(2, result.count + score.ties)

  # tcidu su'e re ve fendi poi nitcu lo mecraide'a
  #   .i le nu tcidu cu cfari bu'u le romoi valsi gi'e ca'o klama ro valsi poi lidne
  var paths = lasts.mapIt(@[(it, n)])
  while paths.len > 0 and result.splits.len < 2:
    let
      path = paths.pop
      (start, finish) = path[^1]
    if start == 0:
      result.splits.add path.reversed.mapIt(words[it[0]][it[1]].get)
      continue
    for before in scores[start][finish].get.befores.reversed:
      paths.add path & (before, start)


func splitChosen(spelling: Spelling, is_parting: bool): Split =
  ## cuxna lo valsi pe le selci'avla
  ##   .i va'o lo nu le lerfu cu se tcidu ta'i pa mulvla kei cuxna pa valsi
  ##   .i va'o lo datcu'a lo ve fendi poi nitcu lo mecraide'a
  ##   .i va'o lo nu `is_parting` jetnu kei slaka bu cu fendi lo slaka
  let whole = spelling.occurrenceWritten(0 .. spelling.letters.high, is_parting)
  if whole.isSome: return Split(splits: @[@[whole.get]], count: 1)
  spelling.splitWritten(is_parting)


func refusalWritten(spelling: Spelling, start: int): ReadingStream =
  ## to'e curmi lo selci'avla poi se fendi fi no valsi
  ##   .i le nu to'e curmi cu zvati le stuzi po'u `start`
  ##   .i va'o lo nu lo valsi poi le genturfa'i cu tcidu ke'a fi le lerfu cu nitcu lo denpa kei le
  ##       nu to'e curmi cu zvati le pamoi lerfu po'u slaka bu poi zvati le stuzi be le denpa
  ##   .i ki'u bo slaka bu cu sinxa no denpa to `CLL 3.3` toi
  ##   .i va'o lo drata le genturfa'i cu to'e curmi ta'i lo nu `readWord` to'e curmi le lerfu
  ##   .i va'o lo drata le nu to'e curmi cu zvati le pamoi barda lerfu noi na mapti lo javni pe
  ##       `CLL 3.9`
  ##
  ## ni'o lo lerfu poi se fendi fi lo cmavo cu se fendi vi ji'a
  ##   .i se ki'u bo slaka bu .a lo barda lerfu po'o cu fanta lo nu le lerfu cu se tcidu
  var bare = spelling
  (bare.breaks, bare.commas) = (newSeq[int](), newSeq[int]())
  let split = bare.splitChosen(is_parting = false)
  if split.count > 0:
    var lo = 0
    for i, word in split.splits[0]:
      let k = spelling.breaks.find(lo)
      if i > 0 and k >= 0 and isPauseNeeded(split.splits[0][i - 1], word):
        # ja'i `CLL 3.3` slaka bu na ka'e du lo denpa
        #   .i `CLL 3.3` cusku zoi gy. cannot be .gy.
        return refuse(Refusal.Comma, spelling.commas[k])
      lo += word.text.len
  let whole = spelling.letters.readWord
  if not whole.is_word and whole.refusal != Refusal.Stream:
    return refuse(whole.refusal, start, whole.detail)
  doAssert spelling.capitals.len > 0, "Written word whose letters read should break 3.9 by capital."
  refuse(Refusal.Stress, spelling.places[spelling.capitals[0]])  # `CLL 3.9`


func refusalCommas(spelling: Spelling, words: openArray[Occurrence]): Option[ReadingStream] =
  ## facki lo pamoi lerfu po'u slaka bu poi na mapti lo javni ja'i lo valsi poi le selci'avla cu
  ##     vasru ke'a
  ##   .i dunda lo nu to'e curmi bu'u le stuzi be le lerfu
  ##   .i le lerfu cu zvati lo karsna gunma pe pa cmavo .a pa gismu .a pa lujvo to `CLL 3.4` toi
  ##   .i ja le lerfu cu zvati lo stuzi poi lo denpa cu bigzva ke'a ne'i lo jbini be re valsi
  ##   .i ki'u bo slaka bu cu selski `CLL 3.3` fo zoi gy. cannot be pronounced as pause .gy.
  var
    lo = 0
    k = 0
  for i, word in words:
    let hi = lo + word.text.len
    while k < spelling.breaks.len and spelling.breaks[k] < hi:
      let
        b = spelling.breaks[k] - lo
        is_broken =
          if b == 0: isPauseNeeded(words[i - 1], word)
          else: word.text[b - 1] in VOWELS_NUCLEUS and word.text[b] in VOWELS_NUCLEUS and
              word.reading.kind in KINDS_DIPHTHONG
      if is_broken: return some(refuse(Refusal.Comma, spelling.commas[k]))
      inc k
    lo = hi
  none(ReadingStream)


func isForeign(word: Occurrence): bool =
  ## jdice lo du'u le valsi pe le porsi cu vasru lo selci'a poi zo zoi .a zo la'o sitna ke'a
  ##   .i le selci'a na lojbo to le zemoi javni pe `CLL 4.9` toi
  not word.reading.is_word and word.reading.refusal == Refusal.Foreign


func pauseBefore(occurrences: openArray[Occurrence], word: Occurrence, is_period: bool): Pause =
  ## cusku lo denpa poi lidne lo valsi poi se lidne `occurrences`
  ##   .i denpa bu cu sinxa le denpa
  ##   .i ja lo javni cu nitcu le denpa
  ##   .i lo selci'a poi se sitna gi'e na lojbo cu se lidne pa denpa gi'e lidne pa denpa to le zemoi
  ##       javni pe `CLL 4.9` toi
  if is_period: return Pause.Written
  let is_needed =
    if occurrences.len == 0: word.isPauseNeededFirst
    elif occurrences[^1].isForeign or word.isForeign: true
    else: isPauseNeeded(occurrences[^1], word)
  if is_needed: Pause.Inferred else: Pause.Absent


func isBoundary*(text: string, at: int): bool =
  ## jdice lo du'u xu kau le lerfu poi zvati `at` cu fendi lo selci'avla
  ##   .i lo kutle'u cu fendi
  ##   .i denpa bu cu fendi va'o po'o lo nu na zvati lo jbini be re lerfu pe `DIGITS_STREAM`
  ##   .i ki'u bo denpa bu poi zvati lo jbini be re lerfu cu sinxa zo pi .a zo pi'e to `D1 a` pe
  ##       `#991` .e `D5 c` pe `#1003` toi
  let c = text[at]
  if c in Whitespace: return true
  if c != '.': return false
  not (at > 0 and text[at - 1] in DIGITS_STREAM and at + 1 < text.len and
      text[at + 1] in DIGITS_STREAM)


func isBoundarySettled*(text: string, at: int): bool =
  ## jdice lo du'u le lerfu poi zvati `at` cu fendi lo selci'avla ca ro nu lo selci'a cu se jmina
  ##   .i denpa bu poi romoi gi'e se lidne pa lerfu pe `DIGITS_STREAM` cu na fendi
  ##   .i ki'u bo lo lerfu poi ba se ciska cu ka'e binxo lo nu denpa bu cu sinxa zo pi .a zo pi'e
  ##   .i lo nu tcidu lo mulselci'a cu pilno `isBoundary` po'o
  text.isBoundary(at) and
    not (at == text.high and text[at] == '.' and at > 0 and text[at - 1] in DIGITS_STREAM)


func wordsLetters(text: string, start, finish: int): ReadingStream =
  ## tcidu lo valsi pe lo selci'avla pe lo stuzi po'u `start ..< finish`
  ##   .i le selci'avla cu vasru no lerfu pe `DIGITS_STREAM` gi'e vasru no sinxa pe `SIGNS_STREAM`
  ##   .i lo denpa na seljdi
  ##   .i to'e curmi lo pagbu poi no javni cu curmi ke'a
  ##   .i le pagbu cu sinxa ja lerfu ja ve fendi
  let refusal_marks = text.refusalMarks(start, finish)
  if refusal_marks.isSome: return refusal_marks.get

  # cuxna lo valsi poi mapti ro sinxa
  #   .i slaka bu cu fendi lo slaka ta'i lo nu `CLL 3.5` fendi lo karsna sepi'o slaka bu
  #   .i se ki'u bo lo brale'u cu basna lo slaka poi slaka bu cu sinxa ke'a
  #   .i ji'a ja'i `CLL 3.3` no ve fendi cu punji lo denpa lo stuzi be slaka bu
  let
    spelling = text.toSpelling(start, finish)
    split = spelling.splitChosen(is_parting = true)
  if split.count == 0: return spelling.refusalWritten(start)
  if split.count > 1:
    let detail = split.splits.mapIt(it.mapIt(it.text).join(" ")).join(", or ")
    # ja'i `CLL 3.3` le genturfa'i na ka'e facki lo pa ve fendi
    return refuse(Refusal.Split, start, detail)
  let refusal_commas = spelling.refusalCommas(split.splits[0])
  if refusal_commas.isSome: return refusal_commas.get
  ReadingStream(is_read: true, occurrences: split.splits[0])


func signAt[T](lut: openArray[(string, T)], text: string, at: int): Option[int] =
  ## dunda lo namcu pe le sinxa pe `lut` poi cfari bu'u `at`
  ##   .i dunda no da va'o lo nu no sinxa pe `lut` cu cfari bu'u `at`
  for k in 0 ..< lut.len:
    if text.continuesWith(lut[k][0], at): return some(k)
  none(int)


func isSignAt(text: string, at: int): bool =
  ## jdice lo du'u pa sinxa pe `SIGNS_STREAM` cu cfari bu'u `at`
  SIGNS_STREAM.anyIt(text.continuesWith(it, at))


func occurrenceSigned(sign, word: string, at: int): Occurrence =
  ## zbasu le valsi poi le sinxa po'u `sign` cu sinxa ke'a gi'e cfari bu'u `at`
  ##   .i le valsi cu vasru ro stuzi pe le sinxa
  ##   .i le lerfu pe le valsi cu du le sinxa
  Occurrence(
    start: at, finish: at + sign.len, text: sign, stress: none(int), reading: word.readWord,
  )


func inferred(words: openArray[string], at: int): seq[Occurrence] =
  ## zbasu lo valsi poi lo jdini sinxa cu sinxa ke'a
  ##   .i ro le valsi cu vasru no stuzi gi'e cfari bu'u `at`
  ##   .i le lerfu pe le valsi cu du le valsi
  for word in words:
    result.add Occurrence(
      start: at, finish: at, text: word, stress: none(int), reading: word.readWord,
    )


func wordsWritten(text: string, start, finish: int): ReadingStream =
  ## tcidu lo valsi pe lo selci'avla pe lo stuzi po'u `start ..< finish`
  ##   .i ro lerfu pe `DIGITS_STREAM` cu du pa valsi poi le genturfa'i cu tcidu ke'a ta'i le cmavo
  ##       poi le lerfu cu sinxa ke'a
  ##   .i se ki'u bo zoi gy. 10moi .gy. cu se tcidu ta'i zo pa .e zo no .e zo moi
  ##   .i denpa bu poi zvati lo jbini be re lerfu cu du pa valsi poi le genturfa'i cu tcidu ke'a
  ##       ta'i zo pi
  ##   .i slaka bu poi se lidne pa lerfu gi'e lidne ci lerfu po'o cu du pa valsi poi le
  ##       genturfa'i cu tcidu ke'a ta'i zo ki'o
  ##   .i `Architect` jdice di'u bu'u `#991` ta'i `D1 a`
  ##   .i ku'i va'o lo nu lo porsi be lo lerfu cu vasru su'o re boi denpa bu kei ro boi denpa bu pe
  ##       le porsi cu sinxa zo pi'e to `runDigits` toi
  ##   .i `Architect` jdice di'u bu'u `#1003` ta'i `D5 c`
  ##   .i lo drata slaka bu poi se lidne pa lerfu cu se to'e curmi to `CLL 3.3` toi
  ##   .i `wordsLetters` tcidu ro drata pagbu
  ##
  ## ni'o lo jdini sinxa poi pencu pa namcu cu sinxa lo jdini klani to `#1003` toi
  ##   .i zo lo .e lo valsi pe le sinxa .e zo be .e zo li cu lidne le namcu
  ##   .i zo be'o .e zo ku cu se lidne le namcu
  ##   .i lo jdini sinxa poi pencu no namcu .a re namcu cu se to'e curmi
  ##   .i `Architect` jdice di'u bu'u `#1003` ta'i `D2 a` .e `D3 a`
  ##   .i ji'a ro namcu cu ponse su'e pa jdini sinxa ki'u lo nu le jdini klani cu vasru lo valsi
  ##       pe pa sinxa po'o
  ##   .i lo jdini sinxa poi pencu lo sinxa pe pa namcu cu pencu le namcu
  ##   .i se ki'u bo zoi gy. -$5 .gy. .e zoi gy. $-5 .gy. cu sinxa lo'u lo rupnu be li ni'u mu
  ##       be'o ku le'u
  ##   .i `Architect` jdice di'u bu'u `#1003` ta'i `D7 c`
  ##   .i ji'a zoi gy. 5€-5 .gy. cu se to'e curmi ki'u lo nu le jdini sinxa cu pencu re namcu to
  ##       `D8 a` pe `#1003` toi
  ##   .i ji'a lo jdini sinxa poi le namcu pe ke'a cu vasru zoi gy. % .gy. cu se to'e curmi mu'u
  ##       zoi gy. $5% .gy. to `D9 b` pe `#1003` toi
  ##
  ## ni'o ro valsi pe le jdini klani cu vasru no stuzi
  ##   .i ro stuzi pe le sinxa cu zvati no valsi
  ##   .i se ki'u bo le porsi be lo valsi cu mintu le porsi be lo stuzi
  ##
  ## ni'o lo sinxa pe `LUT_CMAVO_BY_PREFIX` cu pagbu lo namcu gi'e se tcidu va'o lo nu le ralju
  ##     pagbu be le namcu cu se lidne le sinxa kei .e lo nu no lerfu pe `0` bi'o `9` cu lidne le
  ##     sinxa
  ##   .i le ralju pagbu cu cfari ta'i lo lerfu pe `0` bi'o `9` .a lo sinxa pe
  ##       `LUT_CMAVO_BY_CONSTANT`
  ##   .i ji'a pa jdini sinxa cu ka'e zvati lo jbini be le sinxa .e le ralju pagbu
  ##   .i `Architect` jdice le valsi pe ro sinxa .e le stuzi pe le sinxa bu'u `#1003` ta'i `D4 b`
  ##   .i `Architect` jdice le sinxa pe le namcu poi se lidne le sinxa bu'u `#1003` ta'i `D7 c`
  ##   .i lo sinxa pe `LUT_CMAVO_BY_SUFFIX` cu pagbu lo namcu gi'e se tcidu va'o lo nu lo lerfu pe
  ##       `0` bi'o `9` cu lidne le sinxa kei .e lo nu no lerfu pe `0` bi'o `9` cu se lidne le sinxa
  ##   .i lo sinxa pe `LUT_CMAVO_BY_CONSTANT` cu du pa namcu gi'e se tcidu va'o lo nu no lerfu pe
  ##       `0` bi'o `9` cu pencu le sinxa kei .e lo nu ro sinxa poi pencu le sinxa cu pagbu le namcu
  ##       .a le jdini klani
  ##   .i `Architect` jdice le stuzi pe le re klesi be lo sinxa bu'u `#1003` ta'i `D6 b` .e `D7 c`
  ##   .i ki'u bo bu'u lo drata stuzi le valsi cu sinxa lo drata namcu .a no namcu to `CLL 18.4` toi
  ##   .i lo drata sinxa cu se to'e curmi
  ##   .i lo jdini klani cu vasru ro sinxa pe le namcu to `CLL 18.3` toi
  ##
  ## ni'o le pamoi valsi pe pa sinxa pe lo namcu cu vasru ro stuzi pe le sinxa
  ##   .i ro drata valsi pe le sinxa cu vasru no stuzi gi'e cfari bu'u le stuzi poi se lidne le
  ##       sinxa
  func runDigits(at: int): tuple[finish: int, is_compound: bool] =
    ## jarco le fanmo be le porsi poi krasi bu'u `at` ku'o .e lo du'u le porsi cu vasru su'o re boi
    ##     denpa bu
    ##   .i le porsi cu vasru lo lerfu pe `DIGITS_STREAM` .e denpa bu .e slaka bu poi zvati lo jbini
    ##       be re lerfu pe `DIGITS_STREAM`
    ##   .i le porsi cu fanmo pu `finish`
    var (k, count) = (at, 0)
    while k < finish and (text[k] in DIGITS_STREAM or (text[k] in {'.', ','} and
        text[k - 1] in DIGITS_STREAM and k + 1 < finish and text[k + 1] in DIGITS_STREAM)):
      if text[k] == '.': inc count
      inc k
    (k, count >= 2)

  func isCoreAt(at: int): bool =
    ## jdice lo du'u le ralju pagbu be pa namcu cu cfari bu'u `at`
    ##   .i le ralju pagbu cu cfari ta'i lo lerfu pe `DIGITS_STREAM` .a lo sinxa pe
    ##       `LUT_CMAVO_BY_CONSTANT`
    at < finish and (text[at] in DIGITS_STREAM or LUT_CMAVO_BY_CONSTANT.signAt(text, at).isSome)

  func isNumberAt(at: int): bool =
    ## jdice lo du'u pa namcu cu cfari bu'u `at`
    ##   .i le namcu cu cfari ta'i le ralju pagbu .a lo sinxa pe `LUT_CMAVO_BY_PREFIX` poi se lidne
    ##       le ralju pagbu .a lo jdini sinxa .e le ralju pagbu
    if isCoreAt(at): return true
    let prefix = LUT_CMAVO_BY_PREFIX.signAt(text, at)
    if prefix.isNone: return false
    let
      next = at + LUT_CMAVO_BY_PREFIX[prefix.get][0].len
      currency = LUT_WORDS_BY_SIGN.signAt(text, next)
    isCoreAt(next) or
      (currency.isSome and isCoreAt(next + LUT_WORDS_BY_SIGN[currency.get][0].len))

  func isPercentAt(at: int): bool =
    ## jdice lo du'u zoi gy. % .gy. cu fanmo le namcu poi cfari bu'u `at`
    ##   .i le namcu cu ka'e cfari ta'i lo sinxa pe `LUT_CMAVO_BY_PREFIX` .e lo jdini sinxa
    ##   .i no lerfu pe `DIGITS_STREAM` cu se lidne zoi gy. % .gy. to `D6 b` toi
    var k = at
    let prefix = LUT_CMAVO_BY_PREFIX.signAt(text, k)
    if prefix.isSome: k += LUT_CMAVO_BY_PREFIX[prefix.get][0].len
    let currency = LUT_WORDS_BY_SIGN.signAt(text, k)
    if currency.isSome: k += LUT_WORDS_BY_SIGN[currency.get][0].len
    if k >= finish or text[k] notin DIGITS_STREAM: return false
    k = runDigits(k).finish
    let suffix = LUT_CMAVO_BY_SUFFIX.signAt(text, k)
    if suffix.isNone: return false
    let after = k + LUT_CMAVO_BY_SUFFIX[suffix.get][0].len
    not (after < finish and text[after] in DIGITS_STREAM)

  func isBefore(signs: openArray[string], at: int): bool =
    ## jdice lo du'u pa sinxa pe `signs` cu fanmo bu'u `at`
    signs.anyIt(at - it.len >= start and text.continuesWith(it, at - it.len))

  var
    occurrences: seq[Occurrence]
    at = start
    opened = none(int)  # lo namcu pe le valsi poi krasi le namcu poi ca'o se tcidu
    opening = start  # le stuzi pe le pamoi lerfu pe le namcu
    signed = none(int)  # le jdini sinxa poi lidne le namcu
    ending_digits = start  # le fanmo be le porsi be lo lerfu poi ca'o se tcidu
    is_compound = false  # lo du'u le porsi cu vasru su'o re boi denpa bu
  template closed() =
    # fanmo le namcu
    #   .i jmina zo be'o .e zo ku va'o lo nu lo jdini sinxa cu lidne le namcu
    if signed.isSome: occurrences.add WORDS_AMOUNT_CLOSING.inferred(at)
    (opened, signed) = (none(int), none(int))
  while at < finish:
    if text[at] in DIGITS_STREAM:
      if opened.isNone: (opened, opening) = (some(occurrences.len), at)
      if at >= ending_digits: (ending_digits, is_compound) = runDigits(at)
      occurrences.add Occurrence(
        start: at, finish: at + 1, text: $text[at], stress: none(int),
        reading: LUT_CMAVO_BY_DIGIT[ord(text[at]) - ord('0')].readWord,
      )
      inc at
      continue
    if at > start and text[at - 1] in DIGITS_STREAM and text[at] in {'.', ','}:
      # denpa bu cu zvati ne'i le selci'avla va'o po'o lo nu lo lerfu cu lidne ke'a to
      #     `isBoundary` toi
      var count = 0  # lo klani be lo lerfu poi slaka bu cu lidne ke'a
      while at + 1 + count < finish and text[at + 1 + count] in DIGITS_STREAM: inc count
      if text[at] == ',' and count != 3: return refuse(Refusal.Comma, at)
      let word = (if text[at] == ',': WORD_GROUP elif is_compound: WORD_COMPOUND else: WORD_DECIMAL)
      occurrences.add Occurrence(
        start: at, finish: at + 1, text: $text[at], stress: none(int), reading: word.readWord,
      )
      inc at
      continue
    let
      is_digit_before = at > start and text[at - 1] in DIGITS_STREAM
      prefix = LUT_CMAVO_BY_PREFIX.signAt(text, at)
      suffix = LUT_CMAVO_BY_SUFFIX.signAt(text, at)
      constant = LUT_CMAVO_BY_CONSTANT.signAt(text, at)
    if prefix.isSome:
      let
        (sign, word) = LUT_CMAVO_BY_PREFIX[prefix.get]
        next = at + sign.len  # le stuzi poi se lidne le sinxa
        currency = LUT_WORDS_BY_SIGN.signAt(text, next)  # le jdini sinxa poi se lidne le sinxa
        size = (if currency.isSome: LUT_WORDS_BY_SIGN[currency.get][0].len else: 0)
        is_inner = currency.isSome and isCoreAt(next + size)
      # le ralju pagbu be le namcu cu se lidne le sinxa .a le jdini sinxa
      #   .ije no lerfu pe `0` bi'o `9` cu lidne le sinxa to `D4 b` .e `D7 c` toi
      if is_digit_before or not isNumberAt(at):
        return refuse(Refusal.Sign, at, sign)
      # ro namcu cu ponse su'e pa jdini sinxa to `D2 a` toi
      if is_inner and signed.isSome:
        return refuse(Refusal.Sign, next, LUT_WORDS_BY_SIGN[currency.get][0])
      # le namcu pe le jdini sinxa cu na vasru zoi gy. % .gy. to `D9 b` toi
      if is_inner and isPercentAt(next + size):
        return refuse(Refusal.Sign, next, LUT_WORDS_BY_SIGN[currency.get][0])
      # le jdini klani poi le jdini sinxa cu krasi ke'a cu vasru le sinxa
      if not (signed.isSome and opened.isNone): closed()
      if is_inner:
        occurrences.add (@WORDS_AMOUNT_OPENING & LUT_WORDS_BY_SIGN[currency.get][1] &
          @WORDS_AMOUNT_LINKING).inferred(at)
        signed = currency
      (opened, opening) = (some(occurrences.len), at)
      occurrences.add sign.occurrenceSigned(word, at)
      at = next + (if is_inner: size else: 0)
      continue
    if suffix.isSome:
      let (sign, word) = LUT_CMAVO_BY_SUFFIX[suffix.get]
      # lo lerfu pe `0` bi'o `9` cu lidne le sinxa
      #   .ije no lerfu pe `0` bi'o `9` cu se lidne le sinxa
      if not is_digit_before or (at + sign.len < finish and text[at + sign.len] in DIGITS_STREAM):
        return refuse(Refusal.Sign, at, sign)
      occurrences.add sign.occurrenceSigned(word, at)
      at += sign.len
      continue
    if constant.isSome:
      let
        (sign, words) = LUT_CMAVO_BY_CONSTANT[constant.get]
        after = at + sign.len  # le stuzi poi se lidne le sinxa
      # no lerfu pe `0` bi'o `9` cu pencu le sinxa
      #   .ije ro sinxa poi pencu le sinxa cu pagbu le namcu .a le jdini klani to `D7 c` toi
      if is_digit_before or (after < finish and text[after] in DIGITS_STREAM) or
          (SIGNS_STREAM.isBefore(at) and not (LUT_CMAVO_BY_PREFIX.mapIt(it[0]).isBefore(at) or
            LUT_WORDS_BY_SIGN.mapIt(it[0]).isBefore(at))) or
          (after < finish and text.isSignAt(after) and
            LUT_WORDS_BY_SIGN.signAt(text, after).isNone):
        return refuse(Refusal.Sign, at, sign)
      if opened.isNone: (opened, opening) = (some(occurrences.len), at)
      occurrences.add sign.occurrenceSigned(words[0], at)
      occurrences.add words[1 .. ^1].inferred(after)
      at = after
      continue
    let sign = LUT_WORDS_BY_SIGN.signAt(text, at)
    if sign.isSome:
      let
        size = LUT_WORDS_BY_SIGN[sign.get][0].len
        is_after = opened.isSome  # le namcu poi ca'o se tcidu cu fanmo pu le sinxa
        is_before = isNumberAt(at + size)
      # le sinxa cu pencu pa namcu po'o to `D3 a` toi
      #   .i ji'a le sinxa poi pencu lo sinxa pe pa namcu cu pencu le namcu to `D7 c` toi
      #   .i ro namcu cu ponse su'e pa sinxa to `D2 a` toi
      if is_after == is_before or (is_after and signed.isSome):
        return refuse(Refusal.Sign, at, text.character(at))
      # le namcu pe le sinxa cu na vasru zoi gy. % .gy. to `D9 b` toi
      if (is_after and LUT_CMAVO_BY_SUFFIX.mapIt(it[0]).isBefore(at)) or
          (is_before and isPercentAt(at + size)):
        return refuse(Refusal.Sign, at, text.character(at))
      let words = @WORDS_AMOUNT_OPENING & LUT_WORDS_BY_SIGN[sign.get][1] & @WORDS_AMOUNT_LINKING
      if is_after:
        occurrences.insert(words.inferred(opening), opened.get)
        occurrences.add WORDS_AMOUNT_CLOSING.inferred(at)
        (opened, signed) = (none(int), none(int))
      else:
        occurrences.add words.inferred(at + size)
        signed = sign
      at += size
      continue
    closed()
    let first = at
    while at < finish and text[at] notin DIGITS_STREAM and not text.isSignAt(at): inc at
    let letters = text.wordsLetters(first, at)
    if not letters.is_read: return letters
    occurrences.add letters.occurrences
  closed()
  ReadingStream(is_read: true, occurrences: occurrences)


func quoted(text: string, start: int, delimiter: string): Option[Slice[int]] =
  ## facki lo stuzi be lo selci'a poi se sitna
  ##   .i le selci'a cu cfari bu'u `start` gi'e fanmo pu lo bavla'i se ciska valsi poi ciska
  ##       `delimiter`
  ##   .i lo sinxa poi sruri le selci'a cu selvi'u
  ##   .i dunda no da va'o lo nu no selci'avla poi ciska `delimiter` se lidne to `CLL 19.10` toi
  var at = start
  while at < text.len:
    if text.isBoundary(at):
      inc at
      continue
    let first = at
    while at < text.len and not text.isBoundary(at): inc at
    if text[first ..< at].toLowerAscii.replace(",", "") != delimiter: continue
    var (a, b) = (start, first - 1)
    while a <= b and text.isBoundary(a): inc a
    while b >= a and text.isBoundary(b): dec b
    return some(a .. b)
  none(Slice[int])


func readStream*(text: string, is_lohu = false): ReadingStream =
  ## tcidu lo valsi pe le selci'a ja'i lo javni pe `CLL` po'o
  ##   .i ro valsi cu ponse lo denpa poi lidne le valsi ku'o .e lo nu basna poi le selci'a cu sinxa
  ##       ke'a
  ##   .i to'e curmi bu'u le pamoi pagbu poi no javni cu curmi ke'a
  ##   .i le pagbu cu valsi ja sinxa
  ##   .i cusku le stuzi be le pagbu
  ##
  ## ni'o va'o lo nu `is_lohu` jetnu kei le selci'a cu cfari ne'i lo valsi poi zo lo'u sitna ke'a
  ##   .i lo mivyselci'a cu tcidu le selci'a ta'i di'u ba zo lo'u noi ca'o denpa
  ##
  ## ni'o lo selci'a poi zo zoi .a zo la'o sitna ke'a mulno gi'e du pa valsi pe le porsi gi'e na
  ##     selga'i
  ##   .i lo nu sitna poi zo zo .a zo lo'u zbasu ke'a sitna lo valsi
  ##   .i zo lo'u sitna lo valsi poi lidne zo le'u
  ##   .i se ki'u bo lo cmavo poi se sitna cu galfi no da to `CLL 19.9` toi
  ##
  ## ni'o le porsi cu sisti ba zo fa'o poi no nu sitna cu vasru ke'a
  ##   .i zo fa'o fanmo lo selci'a poi ka'e se tcidu to `CLL 21.1` toi
  var
    occurrences: seq[Occurrence]
    is_period, is_quoting = false
    is_lohu = is_lohu  # lo valsi poi zo lo'u sitna ke'a to le valsi cu lidne zo le'u toi
    # lo nu sitna poi le koivla pe ke'a bavla'i
    #   .i lo koivla poi fanmo le selci'a
    zoi, closing = none(int)
    at = 0
  while at < text.len:
    # klama pa'o lo sinxa poi zvati lo jbini be lo valsi
    #   .i ralte lo du'u denpa bu cu zvati
    if text.isBoundary(at):
      is_period = is_period or text[at] == '.'
      inc at
      continue

    # lebna lo selci'avla poi fanmo pu lo bavla'i sinxa poi zvati lo jbini be lo valsi
    #   .i tcidu lo valsi pe le selci'avla
    let start = at
    while at < text.len and not text.isBoundary(at): inc at
    let written = text.wordsWritten(start, at)
    if not written.is_read: return written
    let words = written.occurrences

    # tcidu le koivla poi fanmo le selci'a poi se sitna
    #   .i le selci'avla cu vasru pa valsi po'o
    #   .i le valsi cu selci'a ta'i le korbi valsi to `CLL 19.10` toi
    if closing.isSome:
      if words.len != 1 or words[0].text != occurrences[closing.get].text:
        return refuse(Refusal.Quotation, start)
      var occurrence = words[0]
      # le zemoi javni pe `CLL 4.9`
      occurrence.pause = (if is_period: Pause.Written else: Pause.Inferred)
      occurrences.add occurrence
      (closing, is_period) = (none(int), false)
      continue

    # jmina ro valsi
    #   .i ro valsi cu ponse lo denpa poi lidne le valsi
    #   .i jersi lo nu sitna poi le valsi cu krasi ja fanmo ke'a
    for i, word in words:
      var occurrence = word
      occurrence.pause = occurrences.pauseBefore(occurrence, is_period = i == 0 and is_period)
      occurrences.add occurrence

      # lo koivla cu fanmo lo selci'avla pe vo'a
      #   .i le selci'a poi le koivla cu sitna ke'a fanmo pu lo nu le koivla cu rapli se ciska to
      #       `CLL 19.10` toi
      if zoi.isSome:
        if i < words.high: return refuse(Refusal.Quotation, words[i + 1].start)
        let span = text.quoted(at, word.text)
        if span.isNone: return refuse(Refusal.Quotation, occurrences[zoi.get].start, word.text)
        let quotation = text[span.get]
        if word.text in quotation.toLowerAscii:
          # ja'i `CLL 19.10` le koivla cu selski fo zoi gy. not found .gy. ne'i le selci'a
          return refuse(Refusal.Quotation, span.get.a)
        occurrences.add Occurrence(
          start: span.get.a, finish: span.get.b + 1, text: quotation, stress: none(int),
          pause: (if '.' in text[at ..< span.get.a]: Pause.Written else: Pause.Inferred),
          reading: Reading(is_word: false, refusal: Refusal.Foreign),
        )
        (zoi, closing, at) = (none(int), some(occurrences.high - 1), span.get.b + 1)
        break

      # zo zo sitna lo bavla'i valsi
      #   .i zo lo'u sitna lo valsi poi lidne zo le'u
      #   .i ku'i zo le'u poi zo zo sitna ke'a fanmo no da to `CLL 19.9` toi
      if is_quoting:
        is_quoting = false
        continue
      let selmaho = word.reading.selmaho
      if is_lohu:
        if selmaho == some(Selmaho.Zo): is_quoting = true
        elif selmaho == some(Selmaho.Lehu): is_lohu = false
        continue
      if selmaho == some(Selmaho.Zo): is_quoting = true
      elif selmaho == some(Selmaho.Lohu): is_lohu = true
      elif selmaho == some(Selmaho.Zoi): zoi = some(occurrences.high)
      elif selmaho == some(Selmaho.Faho):
        # `CLL 19.15`
        #   .i le selci'a cu fanmo
        return ReadingStream(is_read: true, occurrences: occurrences)
    is_period = false
  # `CLL 19.10`
  #   .i no koivla cu zvati
  if zoi.isSome: return refuse(Refusal.Quotation, occurrences[zoi.get].start)
  ReadingStream(is_read: true, occurrences: occurrences)
