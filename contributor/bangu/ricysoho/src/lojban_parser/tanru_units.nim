func withoutGrouping(parts: openArray[Part]): seq[Part] =
  ## vimcu lo cmavo poi zbasu lo girzu po'o
  ##   .i pamoi fa lo nu vimcu zo bo
  ##   .i remoi fa lo nu vimcu zo ke .e zo ke'e vu'o pe ro girzu poi vasru pa tanru pagbu po'o gi'a
  ##       seljo'e no cmavo
  ##   .i le neryraigri cu pamoi
  ##   .i cimoi fa lo nu vimcu zo ke'e poi fanmo no girzu
  ##   .i ba bo lo cmavo poi lidne zo ke poi selvi'u cu jorne lo bavla'i tanru pagbu ta'i lo nu no
  ##       da jbini mu'u lo nu lu se ke ciska li'u se fendi ta'i lu se ciska li'u
  result = parts.filterIt(not it.isWord(WORD_BO))
  var i = result.high
  while i >= 0:
    if result[i].isWord(WORD_KE):
      let stop = result.ending(i)
      if result.countItems(i + 1, stop) == 1 or i == 0 or not result[i - 1].isBinding:
        if stop < result.len: result.delete(stop)
        result.delete(i)
    dec i
  var (kept, depth) = (newSeqOfCap[Part](result.len), 0)
  for part in result:
    if part.isWord(WORD_KE): inc depth
    elif part.isWord(WORD_KEHE):
      if depth == 0: continue
      dec depth
    kept.add part
  result = kept


func tanruUnits*(parts: openArray[Part]): seq[TanruUnit] =
  ## fendi lo pagbu be lo tanru fi lo taurpau
  ##   .i zo ke .e zo ke'e vu'o poi selsni cu selpu'i
  ##   .i lo cmavo poi zbasu lo girzu po'o cu selvi'u
  ##   .i ro pagbu zo'u lo cmavo poi jorne le pagbu cu se fendi fi lo me `Link` pe le pagbu
  ##   .i lo girzu poi lo cmavo pe ke'a se fendi fi no `Link` jorne no da
  ##   .i se ki'u bo zo ke .e zo ke'e pe le girzu cu se vimcu ji'a to `CLL 12.11` toi
  var
    chain: seq[Word]
    dropping: seq[bool]
  for part in parts.withImplied.withClosedBeforeCo.withLoneOpened.withoutGrouping:
    if part.isBinding:
      chain.add part.word
      continue
    let links = chain.toLinks
    chain.setLen 0
    if part.isWord(WORD_KE):
      dropping.add links.len == 0
      if links.len == 0: continue
    elif part.isWord(WORD_KEHE) and dropping.len > 0:
      if dropping.pop: continue
    result.add TanruUnit(part: part, links: links)


