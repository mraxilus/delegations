func isBinding*(part: Part): bool =
  ## jdice lo du'u xu kau `part` du lo cmavo poi jorne lo bavla'i tanru pagbu
  ##   .i le cmavo cu cmavo be `SE` .a `NAhE` .a `NA` .a `NU`
  ##   .i lo pagbu poi no liste cu vasru ke'a du no le cmavo
  part.is_listed and (part.word in WORDS_CONVERSION or part.word in WORDS_OPERATOR)


func toLinks*(chain: openArray[Word]): seq[Link] =
  ## fendi lo cmavo poi jorne pa valsi fi lo me `Link`
  ##   .i lo bartu cu pamoi
  ##   .i ro porsi be lo cmavo be `SE` cu selja'e pa nu galfi lo porsi be lo sumti
  ##   .i lo cmavo poi traji lo ka jibni le valsi cu galfi pu lo drata to `CLL 9.4` toi
  ##   .i va'o lo nu le nu galfi cu selja'e no cenba kei le nu galfi cu selvi'u
  var places = PLACES_SAME
  for i in countdown(chain.high, 0):
    let swapped = chain[i].swapping
    if swapped > 0:
      swap(places[1], places[swapped])
      continue
    if places != PLACES_SAME: result.add Link(places: places)
    places = PLACES_SAME
    result.add Link(places: PLACES_SAME, operator: some(chain[i]))
  if places != PLACES_SAME: result.add Link(places: places)
  result.reverse


func ending(parts: openArray[Part], start: int): int =
  ## facki lo stuzi be zo ke'e poi fanmo lo girzu poi zo ke pe lo stuzi po'u `start` krasi ke'a
  ##   .i lo jalge cu du `parts.len` va'o lo nu no zo ke'e fanmo le girzu to `CLL 5.5` toi
  var depth = 0
  for i in start + 1 ..< parts.len:
    if parts[i].isWord(WORD_KE): inc depth
    elif parts[i].isWord(WORD_KEHE):
      if depth == 0: return i
      dec depth
  parts.len


func countItems(parts: openArray[Part], start, stop: int): int =
  ## kancu lo taurpau poi le girzu cu vasru ke'a ku'o bu'u lo stuzi po'u `start` bi'o lo stuzi po'u
  ##     `stop` ta'i lo nu tcidu lo ni condi pe le girzu po'o
  ##   .i ro pagbu poi jorne no da .e ro girzu poi selvau le girzu cu se kancu pa roi
  var i = start
  while i < stop:
    if parts[i].isWord(WORD_KE):
      inc result
      i = parts.ending(i) + 1
      continue
    if not parts[i].isBinding: inc result
    inc i


func depthAt(parts: openArray[Part], stop: int): int =
  ## kancu lo girzu poi kalri bu'u lo stuzi poi zi lidne lo stuzi po'u `stop`
  for part in parts[0 ..< stop]:
    if part.isWord(WORD_KE): inc result
    elif part.isWord(WORD_KEHE) and result > 0: dec result


func placeOpening(parts: openArray[Part]): int =
  ## facki lo stuzi poi se lidne le porsi
  ##   .i le porsi cu porsi lo cmavo poi jorne gi'e traji lo ka jibni le fanmo gi'e zvati no girzu
  ##       gi'e lidne su'o re taurpau
  ##   .i lo jalge cu du li ni'u pa va'o lo nu no porsi cu mapti
  for at in countdown(parts.len, 1):
    if not parts[at - 1].isBinding or (at < parts.len and parts[at].isBinding): continue
    if parts.depthAt(at) == 0 and parts.countItems(at, parts.len) >= 2: return at
  -1


func withImplied(parts: openArray[Part]): seq[Part] =
  ## punji zo ke .e zo ke'e vu'o poi lo lujvo cu claxu ke'a
  ##   .i va'o lo nu lo te kancu be lo valsi po'u zo na cu se dilcu fi li re fo li pa kei pa lo'u na
  ##       ke le'u selpu'i lo stuzi poi lidne le multau
  ##   .i va'o lo nu le te kancu cu se dilcu fi li re fo li no kei no da selpu'i
  ##   .i ki'u bo zo na natfe lo mulbri
  ##   .i ji'a lo re zo na galfi no da to `CLL 15.2` toi
  ##
  ## ni'o zo ke se lidne lo pamoi be lo re lamyma'o be `SE` to `CLL 12.11` toi
  ##   .i zo kei se tcidu ta'i zo ke'e poi fanmo lo girzu poi zo ke krasi ke'a
  ##   .i zo ke se lidne le cmavo be `NU` poi traji lo ka jibni gi'e ka'e selfa'o zo kei to
  ##       `CLL 21.1` .e le javni pe li pamure toi
  ##   .i zo kei selvi'u va'o lo nu no cmavo be `NU` cu lidne zo kei
  let plain = parts.filterIt(not it.isWord(WORD_NA))
  if (parts.len - plain.len) mod 2 == 1: result.add [WORD_NA.toPart, WORD_KE.toPart]
  var abstractions: seq[int]
  for i, part in plain:
    if part.isWord(WORD_KEI):
      if abstractions.len > 0:
        result.insert(WORD_KE.toPart, abstractions.pop + 1)
        result.add WORD_KEHE.toPart
      continue
    if part.isAbstraction: abstractions.add result.len
    result.add part
    if i + 1 < plain.len and part.swapping > 0 and plain[i + 1].swapping > 0:
      result.add WORD_KE.toPart


func withClosedBeforeCo(parts: openArray[Part]): seq[Part] =
  ## rinka lo nu ro girzu poi kalri bu'u zo co ganlo sepi'o zo ke'e noi lidne zo co
  ##   .i ki'u bo no girzu cu vasru zo co to `CLL 5.8` toi
  var depth = 0
  for part in parts:
    if part.isWord(WORD_KE): inc depth
    elif part.isWord(WORD_KEHE) and depth > 0: dec depth
    elif part.isWord(WORD_CO):
      for _ in 1 .. depth: result.add WORD_KEHE.toPart
      depth = 0
    result.add part


func withLoneOpened(parts: openArray[Part]): seq[Part] =
  ## ro zo ke'e poi fanmo no girzu zo'u punji zo ke lo stuzi poi se lidne le porsi be lo cmavo poi
  ##     jorne be'o poi traji lo ka jibni le valsi
