      which of her hands, differs. The two two-hand holds become one
      geometry offset by her facing: a half turn puts either pair in the X,
      with her <b>away</b> for the cross-name pair and <b>facing</b> for the
      same-name one. Neither X is a hold of its own. Counted from face to
      face the away rest is <b>@ &#8722;&#189;</b>; the body sim reads her
      arm there as open — the hand at her side — and as the low lock, led,
      only at the whole turn.</p>
