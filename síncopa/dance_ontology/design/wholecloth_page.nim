<section class="plate">
  <p class="pnum">plate 4 · the modifiers</p>
  <h2>What one arm can do, at its height</h2>
  <p>A modifier belongs to <b>one arm of one dancer</b> — either dancer —
  and it rides inside that hand's own name:
  <span class="m">Left-Lock-Low to right</span> is the lead's Left, locked
  low, holding the follow's right. Two drawing rules carry the anatomy.
  <b>An arm goes around the outside of the body circle</b>, leaving its
  mark at the angle that lets it hug the rim — only an <i>above</i> hand
  may sit inside, and never over the chevron. And <b>only a held arm is
  drawn</b>: under or over her other arm is said by the height and by how
  close the rope hugs the body — low and tight is under, high and wide is
