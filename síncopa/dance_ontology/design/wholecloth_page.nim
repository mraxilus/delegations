<section class="plate">
  <p class="pnum">plate 6 · the moves</p>
  <h2>Two primitives, four named compounds</h2>
  <p>Everything that changes what is held reduces to two primitives; the
  four starred helpers are worth their names because a lead thinks of each
  as one action. The starred ones keep contact through a trace — a hand
  travelling <b>on</b> the partner, not through the air. Definitions only
  for now: the symbols for these are deliberately unchosen, and the next
  round will offer candidates.</p>
  <div class="verbs">
    <div class="verb"><div class="term">collect <span class="k">primitive</span></div>
      <p>Join a connection: a lead hand takes a follow hand.</p></div>
    <div class="verb"><div class="term">drop <span class="k">primitive</span></div>
      <p>Release it: the connection ends, both hands go free.</p></div>
    <div class="verb"><div class="term">flick <span class="k">compound &#42;</span></div>
      <p>A drop with momentum: the hand is sent, not just let go.</p></div>
    <div class="verb"><div class="term">trace <span class="k">compound &#42;</span></div>
      <p>Slide a held connection along the partner's body: contact, moving.</p></div>
    <div class="verb"><div class="term">place <span class="k">compound &#42;</span></div>
      <p>Collect, then drop somewhere new — traced the whole way, with
      nothing in the path.</p></div>
    <div class="verb"><div class="term">cut <span class="k">compound &#42;</span></div>
      <p>Drop, then collect past an obstruction — an arm, torso, or neck in
      the way; the trace carries the contact over it.</p></div>
  </div>
  <div class="note">
    <p><b>Where the safety edge lives:</b> among these moves. Any move that
    would produce a <span class="m">…-Lock-Low</span> hand must arrive from
    a low carriage — collect low and turn, or trace down first. The state
    itself is fine; the forbidden thing is one particular way in.</p>
  </div>
