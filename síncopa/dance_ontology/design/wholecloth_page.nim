##   Page was drawn by hand as HTML; repository audit reads only registered file
##     kinds (Nim among them, HTML not), so markup is hosted here as one string
##     constant, and `design/wholecloth.nim` writes page from it.
##     Cost: audit cannot see inside string, so its five embedded comments (one
##       HTML header, one CSS banner, three SVG row labels) are kept telegraphic
##       by hand, and every line is kept within width by
##       `reflow_wholecloth.py`, which breaks lines only at whitespace that
##       rendering ignores: between tags, between attributes (hanging at two
##       spaces where nothing else fits), inside CSS, inside list-valued
##       attributes (`d`, `points`, `class`, `style`), and inside `aria-label`
##       prose, whose whitespace accessible-name computation collapses (checked:
##       accessibility trees of original and rebuilt page are equal).  One line,
##       turn ticks, held no whitespace to break at, so its character references
##       are decoded to characters, which parser does anyway (checked: DOM of
##       both pages equal outside turns panel, whitespace collapsed).  Never edit
##       reflowed lines by hand; rerun script.
##     Cost: one Google Fonts request is single URL wider than any line may be,
##       so `MARKUP` is three pieces joined at compile time around `FONTS_HREF`
##       rather than one literal.
##   Two marker lines stand where page's scripts were, each replaced by splicer
